// NewWrapResponseWriter wraps an http.ResponseWriter, returning a proxy that allows you to
// hook into various parts of the response process.
func NewWrapResponseWriter(w http.ResponseWriter, protoMajor int) WrapResponseWriter {
	_, fl := w.(http.Flusher)
	_, rf := w.(io.ReaderFrom)

	bw := basicWriter{ResponseWriter: w}

	if protoMajor == 2 {
		// HTTP/2 connections cannot be hijacked, but the writer may
		// support server push.
		_, ps := w.(http.Pusher)
		switch {
		case fl && ps && rf:
			return &http2FancyWriter{bw}
		case fl && ps:
			return &flushPusherWriter{bw}
		case fl && rf:
			return &flushReaderFromWriter{bw}
		case ps && rf:
			return &pusherReaderFromWriter{bw}
		case ps:
			return &pusherWriter{bw}
		}
	} else {
		_, hj := w.(http.Hijacker)
		switch {
		case fl && hj && rf:
			return &httpFancyWriter{bw}
		case fl && hj:
			return &flushHijackWriter{bw}
		case fl && rf:
			return &flushReaderFromWriter{bw}
		case hj && rf:
			return &hijackReaderFromWriter{bw}
		case hj:
			return &hijackWriter{bw}
		case rf:
			return &readerFromWriter{bw}
		}
	}

	if fl {
		return &flushWriter{bw}
	}
	if rf {
		return &readerFromWriter{bw}
	}

	return &bw
}

// WrapResponseWriter is a proxy around an http.ResponseWriter that allows you to hook
// into various parts of the response process.
type WrapResponseWriter interface {
	http.ResponseWriter
	// Status returns the HTTP status of the request, or 0 if one has not
	// yet been sent.
	Status() int
	// BytesWritten returns the total number of bytes sent to the client.
	BytesWritten() int
	// Tee causes the response body to be written to the given io.Writer in
	// addition to proxying the writes through. Only one io.Writer can be
	// tee'd to at once: setting a second one will overwrite the first.
	// Writes will be sent to the proxy before being written to this
	// io.Writer. It is illegal for the tee'd writer to be modified
	// concurrently with writes.
	Tee(io.Writer)
	// Unwrap returns the original proxied target.
	Unwrap() http.ResponseWriter
	// Discard causes all writes to the original ResponseWriter be discarded,
	// instead writing only to the tee'd writer if it's set.
	// Flush calls also do not reach the original ResponseWriter.
	// The caller is responsible for calling WriteHeader and Write on the
	// original ResponseWriter once the processing is done.
	Discard()
}

// basicWriter wraps a http.ResponseWriter that implements the minimal
// http.ResponseWriter interface.
type basicWriter struct {
	http.ResponseWriter
	tee         io.Writer
	code        int
	bytes       int
	wroteHeader bool
	discard     bool
}

func (b *basicWriter) WriteHeader(code int) {
	if code >= 100 && code <= 199 && code != http.StatusSwitchingProtocols {
		if !b.discard {
			b.ResponseWriter.WriteHeader(code)
		}
	} else if !b.wroteHeader {
		b.code = code
		b.wroteHeader = true
		if !b.discard {
			b.ResponseWriter.WriteHeader(code)
		}
	}
}

func (b *basicWriter) Write(buf []byte) (n int, err error) {
	b.maybeWriteHeader()
	if !b.discard {
		n, err = b.ResponseWriter.Write(buf)
		if b.tee != nil {
			_, err2 := b.tee.Write(buf[:n])
			// Prefer errors generated by the proxied writer.
			if err == nil {
				err = err2
			}
		}
	} else if b.tee != nil {
		n, err = b.tee.Write(buf)
	} else {
		n, err = io.Discard.Write(buf)
	}
	b.bytes += n
	return n, err
}

func (b *basicWriter) maybeWriteHeader() {
	if !b.wroteHeader {
		b.WriteHeader(http.StatusOK)
	}
}

func (b *basicWriter) flush() {
	b.maybeWriteHeader()
	if !b.discard {
		b.ResponseWriter.(http.Flusher).Flush()
	}
}

func (b *basicWriter) Status() int {
	return b.code
}

func (b *basicWriter) BytesWritten() int {
	return b.bytes
}

func (b *basicWriter) Tee(w io.Writer) {
	b.tee = w
}

func (b *basicWriter) Unwrap() http.ResponseWriter {
	return b.ResponseWriter
}

func (b *basicWriter) Discard() {
	b.discard = true
}

// readFrom is the shared implementation behind the ReadFrom method of the
// wrapper types that expose io.ReaderFrom. It is intentionally unexported:
// basicWriter itself must not satisfy io.ReaderFrom, only the wrappers whose
// underlying ResponseWriter does.
func (b *basicWriter) readFrom(r io.Reader) (int64, error) {
	if b.tee != nil || b.discard {
		// Route through basicWriter.Write so that the tee and discard semantics
		// are honored (the fast ReaderFrom path below would bypass both, writing
		// straight to the original ResponseWriter). basicWriter.Write already
		// increments basicWriter.bytes, so we must NOT add n again here (that
		// would double-count).
		n, err := io.Copy(b, r)
		return n, err
	}
	rf := b.ResponseWriter.(io.ReaderFrom)
	b.maybeWriteHeader()
	n, err := rf.ReadFrom(r)
	b.bytes += int(n)
	return n, err
}

// flushWriter ...
type flushWriter struct {
	basicWriter
}

func (f *flushWriter) Flush() {
	f.basicWriter.flush()
}

var _ http.Flusher = &flushWriter{}

// hijackWriter ...
type hijackWriter struct {
	basicWriter
}

func (f *hijackWriter) Hijack() (net.Conn, *bufio.ReadWriter, error) {
	hj := f.basicWriter.ResponseWriter.(http.Hijacker)
	return hj.Hijack()
}

var _ http.Hijacker = &hijackWriter{}

