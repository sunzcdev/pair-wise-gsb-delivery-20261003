package plugin

const (
	// EnvUnixSocketDir specifies the directory that _plugins_ should create unix
	// sockets in. Does not affect client behavior.
	EnvUnixSocketDir = "PLUGIN_UNIX_SOCKET_DIR"

	// EnvUnixSocketGroup specifies the owning, writable group to set for Unix
	// sockets created by _plugins_. Does not affect client behavior.
	EnvUnixSocketGroup = "PLUGIN_UNIX_SOCKET_GROUP"

	// EnvHandshakeNetwork is set by the client to tell the plugin the
	// network type ("unix" or "tcp") of the dedicated handshake channel
	// offered for this launch. If it is not set, the plugin should use the
	// legacy stdout handshake.
	EnvHandshakeNetwork = "PLUGIN_HANDSHAKE_NETWORK"

	// EnvHandshakeAddr is set by the client to tell the plugin the address
	// of the client's handshake listener for this launch.
	EnvHandshakeAddr = "PLUGIN_HANDSHAKE_ADDR"

	// EnvHandshakeToken is a one-time random credential generated by the
	// client for a single plugin launch. The plugin must present it over
	// the handshake channel to authenticate itself before the client will
	// accept the handshake.
	EnvHandshakeToken = "PLUGIN_HANDSHAKE_TOKEN"

	envMultiplexGRPC = "PLUGIN_MULTIPLEX_GRPC"
)
