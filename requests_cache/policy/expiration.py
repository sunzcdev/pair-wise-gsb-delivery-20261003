"""Utility functions for parsing and converting expiration values"""

from datetime import datetime, timedelta, timezone
from email.utils import parsedate_to_datetime
from fnmatch import fnmatch
from logging import getLogger
from math import ceil
from typing import Optional
from typing import Pattern as RegexPattern

from .._utils import try_int
from . import ExpirationPattern, ExpirationPatterns, ExpirationTime

# Special client-side expiration values that may be set by either headers or keyword args
DO_NOT_CACHE = 0x0D0E0200020704  # Per RFC 4824
EXPIRE_IMMEDIATELY = 0
NEVER_EXPIRE = -1

logger = getLogger(__name__)

# Maximum tolerated difference between the local clock and the origin server's ``Date`` header
# (RFC 9111, section 4.2.3: apparent age may be negative due to clock skew or resolution)
CLOCK_SKEW_SECONDS = 60


def get_expiration_datetime(
    expire_after: ExpirationTime,
    start_time: Optional[datetime] = None,
    negative_delta: bool = False,
    ignore_invalid_httpdate: bool = False,
) -> Optional[datetime]:
    """Convert an expiration value in any supported format to an absolute datetime"""
    # Invalid dates MUST be treated as 'already expired' (RFC 2616, section 14.21)
    # Expires headers arrive as integer strings (eg. '0'...or even '-1' if you are Azure...)
    if (
        isinstance(expire_after, str)
        and expire_after
        and (expire_after[1:] if expire_after[0] == '-' else expire_after).isdigit()
    ):
        expire_after = EXPIRE_IMMEDIATELY
    # Never expire (or do not cache, in which case expiration won't be used)
    if expire_after is None or expire_after in [NEVER_EXPIRE, DO_NOT_CACHE]:
        return None
    # Expire immediately
    elif try_int(expire_after) == EXPIRE_IMMEDIATELY:
        return start_time or utcnow()
    # Already a datetime or httpdate str (allowed for headers only)
    if isinstance(expire_after, str):
        expire_after_dt = _parse_http_date(expire_after)
        if not expire_after_dt and not ignore_invalid_httpdate:
            raise ValueError(f'Invalid HTTP date: {expire_after}')
        return expire_after_dt
    elif isinstance(expire_after, datetime):
        return expire_after.astimezone(timezone.utc)

    # Otherwise, it must be a timedelta or time in seconds
    if not isinstance(expire_after, timedelta):
        expire_after = timedelta(seconds=expire_after)
    if negative_delta:
        expire_after = -expire_after
    return (start_time or utcnow()) + expire_after


def get_expiration_seconds(expire_after: ExpirationTime) -> int:
    """Convert an expiration value in any supported format to an expiration time in seconds"""
    expires = get_expiration_datetime(expire_after, ignore_invalid_httpdate=True)
    return ceil((expires - utcnow()).total_seconds()) if expires else NEVER_EXPIRE


def get_url_expiration(
    url: Optional[str], urls_expire_after: Optional[ExpirationPatterns] = None
) -> ExpirationTime:
    """Check for a matching per-URL expiration, if any"""
    if not url:
        return None

    for pattern, expire_after in (urls_expire_after or {}).items():
        if _url_match(url, pattern):
            logger.debug(f'URL {url} matched pattern "{pattern}": {expire_after}')
            return expire_after
    return None


def add_tzinfo(dt: Optional[datetime]) -> Optional[datetime]:
    """Add a UTC timezone to a datetime object, if it doesn't already have one. This is used mainly
    during deserialization for backends that don't store timezone info.
    """
    if dt and dt.tzinfo is None:
        return dt.replace(tzinfo=timezone.utc)
    return dt


def get_http_date(headers) -> Optional[datetime]:
    """Parse an HTTP ``Date`` header, if present and valid.

    A missing or unparseable date is returned as ``None`` rather than raising; callers treat it
    as if the response had just been generated by the origin.
    """
    date_value = headers.get('Date') if hasattr(headers, 'get') else None
    if not date_value:
        return None
    return _parse_http_date(date_value)


def get_age_header(headers) -> int:
    """Parse an ``Age`` header as a non-negative number of seconds.

    Invalid, non-numeric, or negative values are treated as zero so a malformed or hostile
    ``Age`` header can never extend a response's lifetime (RFC 9111, section 5.1).
    """
    age_value = headers.get('Age') if hasattr(headers, 'get') else None
    age = try_int(age_value)
    return age if age is not None and age >= 0 else 0


def get_corrected_initial_age(
    headers,
    received_at: Optional[datetime] = None,
) -> int:
    """Calculate the corrected initial age of a response when it was received (RFC 9111,
    section 4.2.3).

    This unifies the origin ``Date`` header, the upstream ``Age`` header, the local receive time,
    and clock skew:

    * ``apparent_age`` is the time between the origin ``Date`` and local receive time. It is
      always clamped to zero, so a future ``Date`` (whether from minor clock skew within
      :data:`CLOCK_SKEW_SECONDS` or a more badly skewed clock) can never produce a negative age
      or extend the lifetime.
    * The result is at least the (validated, non-negative) ``Age`` header value, so an age
      reported by an upstream proxy always shortens--never extends--the remaining lifetime.
    """
    received_at = received_at or utcnow()
    age_value = get_age_header(headers)
    date_value = get_http_date(headers)

    if date_value is None:
        apparent_age = 0
    else:
        apparent_age = int((received_at - date_value).total_seconds())
        if apparent_age < 0:
            logger.debug(
                'Response Date is %s seconds in the future (skew tolerance %ss); '
                'clamping apparent age to zero',
                -apparent_age,
                CLOCK_SKEW_SECONDS,
            )
        apparent_age = max(0, apparent_age)

    return max(apparent_age, age_value)


def get_age_adjusted_expiration(
    headers,
    expire_after: ExpirationTime,
    received_at: Optional[datetime] = None,
) -> Optional[datetime]:
    """Compute an absolute expiration that accounts for the age a response already had when it was
    received, including time spent in upstream proxy caches.

    ``expire_after`` may be any supported expiration value, including an absolute datetime as
    produced by :py:func:`get_expiration_datetime`. When the response carries no usable age
    information (no ``Age``/``Date`` headers), the expiration is returned unchanged, so a
    client-side ``expire_after`` keeps its established precedence and behavior.

    When age information exists, a relative lifetime (e.g. ``max-age``) is shortened by the
    corrected initial age, keeping it and the stale windows aligned with the response's *current*
    age. An absolute expiration (e.g. an ``Expires`` header) is a fixed point in time and is
    returned as-is, since RFC 9111 compares current age against it directly.
    """
    received_at = received_at or utcnow()
    initial_age = get_corrected_initial_age(headers, received_at)

    if expire_after is None or expire_after in [NEVER_EXPIRE, DO_NOT_CACHE]:
        return None

    # An already-absolute expiration is a fixed point in time; never shift it on local clock/age
    if _is_absolute_expiration(expire_after):
        return get_expiration_datetime(expire_after, ignore_invalid_httpdate=True)

    base_expires = get_expiration_datetime(expire_after, start_time=received_at)
    if base_expires is None:
        return None
    # Immediate expiration is already at the receive time; subtracting age would only push the
    # fixed "expired now" point into the past without changing the freshness decision
    if expire_after == EXPIRE_IMMEDIATELY:
        return base_expires
    if initial_age <= 0:
        return base_expires
    return base_expires - timedelta(seconds=initial_age)


def get_revalidated_expiration(
    expire_after: ExpirationTime,
    corrected_age: int,
    received_at: Optional[datetime] = None,
) -> Optional[datetime]:
    """Compute the expiration after a 304 revalidation using the unified corrected content age.

    The 304 response has no body, so the freshness lifetime (a relative value such as
    ``max-age``) starts at the revalidation time but the already-accrued content age is
    subtracted, preventing stale content from gaining a full fresh lifetime. Absolute values
    (datetimes or HTTP-date strings such as ``Expires``) remain fixed points in time.
    """
    received_at = received_at or utcnow()
    if expire_after is None or expire_after in [NEVER_EXPIRE, DO_NOT_CACHE]:
        return None

    # Absolute expiration is a fixed point in time and must not shift on revalidation
    if _is_absolute_expiration(expire_after):
        return get_expiration_datetime(expire_after, ignore_invalid_httpdate=True)

    base_expires = get_expiration_datetime(expire_after, start_time=received_at)
    if base_expires is None or corrected_age <= 0:
        return base_expires
    if expire_after == EXPIRE_IMMEDIATELY:
        return base_expires
    return base_expires - timedelta(seconds=corrected_age)


def _is_numeric_string(value: str) -> bool:
    return (value[1:] if value.startswith('-') else value).isdigit()


def _is_absolute_expiration(expire_after: ExpirationTime) -> bool:
    """Whether an expiration value is an absolute point in time (datetime or HTTP-date string).

    Numeric strings (e.g. ``'0'``/``'-1'`` from an ``Expires`` header) are relative sentinels.
    """
    return isinstance(expire_after, datetime) or (
        isinstance(expire_after, str) and not _is_numeric_string(expire_after)
    )


def utcnow() -> datetime:
    """Get the current time in UTC (timezone-aware)"""
    return datetime.now(timezone.utc)


def _parse_http_date(value: str) -> Optional[datetime]:
    """Attempt to parse an HTTP (RFC 5322-compatible) timestamp"""
    try:
        expire_after = parsedate_to_datetime(value)
        return expire_after.astimezone(timezone.utc)
    # Can occur when using a cache created with requests-cache <=1.1
    except (TypeError, ValueError):
        logger.debug(f'Failed to parse timestamp: {value}')
        return None


def _url_match(url: str, pattern: ExpirationPattern) -> bool:
    """Determine if a URL matches a pattern

    Args:
        url: URL to test. Its base URL (without protocol) will be used.
        pattern: Glob pattern to match against. A recursive wildcard will be added if not present

    Example:
        >>> url_match('https://httpbin.org/delay/1', 'httpbin.org/delay')
        True
        >>> url_match('https://httpbin.org/stream/1', 'httpbin.org/*/1')
        True
        >>> url_match('https://httpbin.org/stream/2', 'httpbin.org/*/1')
        False
        >>> url_match('https://httpbin.org/stream/2', re.compile('httpbin.org/*/\\d+'))
        True
        >>> url_match('https://httpbin.org/stream/x', re.compile('httpbin.org/*/\\d+'))
        False
    """
    if isinstance(pattern, RegexPattern):
        match = pattern.search(url)
        return match is not None
    else:
        url = url.split('://')[-1]
        pattern = pattern.split('://')[-1].rstrip('*') + '**'
        return fnmatch(url, pattern)
