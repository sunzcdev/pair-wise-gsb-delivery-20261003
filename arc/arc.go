// Package arc creates and verifies Authenticated Received Chain (ARC) sets,
// as specified in RFC 8617.
//
// A valid cryptographic chain is not an automatic delivery decision. Verify
// reports the latest cv value and calls VerifyOptions.IsDomainTrusted for each
// sealing domain, but the caller must interpret those results with local
// policy. A chain can be cryptographically valid while signed only by
// untrusted domains, and a valid chain can carry cv=fail.
package arc

import (
	"crypto"
	"encoding/base64"
	"fmt"
	"io"
	"strconv"
	"strings"
	"time"

	"github.com/emersion/go-msgauth/authres"
	"github.com/emersion/go-msgauth/dkim"
)

const (
	aarHeaderName = "arc-authentication-results"
	amsHeaderName = "arc-message-signature"
	asHeaderName  = "arc-seal"

	aarHeaderFieldName = "ARC-Authentication-Results"
	amsHeaderFieldName = "ARC-Message-Signature"
	asHeaderFieldName  = "ARC-Seal"
	crlf               = "\r\n"

	defaultCanonicalization = dkim.CanonicalizationRelaxed
	maxInstances            = 50
)

// ChainValue is the cv value asserted by an ARC-Seal header.
type ChainValue string

const (
	// ChainNone is used only by the first ARC set.
	ChainNone ChainValue = "none"
	// ChainPass records that the preceding chain passed local validation.
	ChainPass ChainValue = "pass"
	// ChainFail records that the preceding chain failed local validation.
	ChainFail ChainValue = "fail"
)

// SealOptions configures an ARC set generated by Seal.
type SealOptions struct {
	// Domain and Selector identify the sealing domain's DKIM key.
	Domain   string
	Selector string
	// Signer signs AMS and AS.
	Signer crypto.Signer
	// Instance is the new one-based ARC instance number.
	Instance int
	// Chain is the local chain assessment written to the AS cv tag.
	Chain ChainValue
	// AuthServID identifies the authentication service creating AAR.
	AuthServID string
	// Results are formatted into AAR.
	Results []authres.Result
	// HeaderKeys adds regular header fields to the AMS h tag. From is always signed.
	HeaderKeys  []string
	Expiration  time.Time
	QueryMethod dkim.QueryMethod
}

// Seal reads an RFC 5322 message and prepends an AAR, AMS and AS set. It does
// not authenticate the inbound message or decide whether the chain is trusted;
// callers must supply those assessments through Chain and Results.
func Seal(w io.Writer, r io.Reader, options *SealOptions) error {
	if err := validateSealOptions(options); err != nil {
		return err
	}
	fields, bodyReader, err := dkim.ReadMessageHeader(r)
	if err != nil {
		return err
	}
	body, err := io.ReadAll(bodyReader)
	if err != nil {
		return err
	}
	if err := checkSealInstance(fields, options.Instance); err != nil {
		return err
	}
	algorithm, err := dkim.AlgorithmForKey(options.Signer.Public())
	if err != nil {
		return err
	}
	bodyHash, err := hashBody(defaultCanonicalization, body)
	if err != nil {
		return err
	}

	aarValue := fmt.Sprintf(" i=%d; %s", options.Instance, authres.Format(options.AuthServID, options.Results))
	aarField := formatHeaderField(aarHeaderFieldName, aarValue)
	amsParams := map[string]string{
		"b":  "",
		"i":  strconv.Itoa(options.Instance),
		"v":  "1",
		"a":  algorithm,
		"c":  string(defaultCanonicalization) + "/" + string(defaultCanonicalization),
		"bh": base64.StdEncoding.EncodeToString(bodyHash),
		"d":  options.Domain,
		"s":  options.Selector,
		"t":  strconv.FormatInt(time.Now().Unix(), 10),
		"h":  strings.Join(amsHeaderKeys(fields, options.HeaderKeys, options.Instance), ":"),
	}
	if !options.Expiration.IsZero() {
		amsParams["x"] = strconv.FormatInt(options.Expiration.Unix(), 10)
	}
	if options.QueryMethod != "" {
		amsParams["q"] = string(options.QueryMethod)
	}

	fieldsWithAAR := append(dkim.Header{aarField}, fields...)
	amsField := dkim.FormatSignatureParams(amsHeaderFieldName, amsParams)
	fieldsWithAMS := append(dkim.Header{amsField}, fieldsWithAAR...)
	hashedHeaders, err := hashMessageSignature(defaultCanonicalization, fieldsWithAMS, amsParams["h"], amsField)
	if err != nil {
		return err
	}
	signature, err := dkim.SignHash(options.Signer, crypto.SHA256, hashedHeaders)
	if err != nil {
		return err
	}
	amsParams["b"] = base64.StdEncoding.EncodeToString(signature)
	amsField = dkim.FormatSignatureParams(amsHeaderFieldName, amsParams)

	asParams := map[string]string{
		"i":  strconv.Itoa(options.Instance),
		"v":  "1",
		"a":  algorithm,
		"b":  "",
		"cv": string(options.Chain),
		"d":  options.Domain,
		"s":  options.Selector,
		"t":  strconv.FormatInt(time.Now().Unix(), 10),
		"h":  strings.Join(sealHeaderKeys(fieldsWithAAR, options.Instance), ":"),
	}
	asField := dkim.FormatSignatureParams(asHeaderFieldName, asParams)
	fieldsWithAS := append(dkim.Header{asField, amsField}, fieldsWithAAR...)
	hashedSeal, err := hashSeal(defaultCanonicalization, fieldsWithAS, asParams["h"], asField)
	if err != nil {
		return err
	}
	sealSignature, err := dkim.SignHash(options.Signer, crypto.SHA256, hashedSeal)
	if err != nil {
		return err
	}
	asParams["b"] = base64.StdEncoding.EncodeToString(sealSignature)
	asField = dkim.FormatSignatureParams(asHeaderFieldName, asParams)

	if _, err := io.WriteString(w, asField+amsField+aarField); err != nil {
		return err
	}
	for _, field := range fields {
		if _, err := io.WriteString(w, field); err != nil {
			return err
		}
	}
	if _, err := io.WriteString(w, crlf); err != nil {
		return err
	}
	_, err = w.Write(body)
	return err
}
