package mysql

// Session state tracking
// https://dev.mysql.com/doc/dev/mysql-server/latest/page_protocol_basic_ok_packet.html#sect_protocol_basic_ok_packet_sessstate

// SessionTrackType identifies the kind of a session state change reported by
// the server in an OK packet when CLIENT_SESSION_TRACK is enabled.
type SessionTrackType int

const (
	SessionTrackSystemVariables SessionTrackType = iota
	SessionTrackSchema
	SessionTrackStateChange
	SessionTrackGTIDs
	SessionTrackTransactionCharacteristics
	SessionTrackTransactionState
)

// SessionStateChange describes a single session state change reported by the
// server. Callers receive these in a structured form and never have to parse
// protocol packets themselves.
type SessionStateChange struct {
	Type SessionTrackType
	// Name is the system variable name. It is only set for
	// SessionTrackSystemVariables.
	Name string
	// Value is the reported payload: the new variable value, the new default
	// schema, a GTID set, or a transaction state string, depending on Type.
	Value string
}

// SessionState is the connection-level view of the session state changes
// accumulated since the connection was established.
type SessionState struct {
	// Schema is the current default schema, if the server reported a change.
	Schema string
	// SystemVars maps changed system variable names to their new values.
	SystemVars map[string]string
	// GTIDs lists the GTID sets generated by transactions on this connection.
	GTIDs []string
}

// SessionStater is implemented by driver connections that expose tracked
// session state. Retrieve it from a *sql.Conn via Raw:
//
//	var state mysql.SessionState
//	err := conn.Raw(func(c any) error {
//		if sc, ok := c.(mysql.SessionStater); ok {
//			state = sc.SessionState()
//		}
//		return nil
//	})
type SessionStater interface {
	SessionState() SessionState
}

// SessionState returns a snapshot of the session state tracked on this
// connection. The result is a copy; mutating it does not affect the
// connection.
func (mc *mysqlConn) SessionState() SessionState {
	state := SessionState{Schema: mc.sessionState.Schema}
	if len(mc.sessionState.SystemVars) > 0 {
		state.SystemVars = make(map[string]string, len(mc.sessionState.SystemVars))
		for name, value := range mc.sessionState.SystemVars {
			state.SystemVars[name] = value
		}
	}
	state.GTIDs = append(state.GTIDs, mc.sessionState.GTIDs...)
	return state
}

// readOkSessionState parses the optional session state information of an OK
// packet (also used as an EOF replacement when CLIENT_DEPRECATE_EOF is
// enabled). pos must point to the warning count field. Parsed changes are
// staged, not published; see commitSessionState.
func (mc *mysqlConn) readOkSessionState(data []byte, pos int) error {
	if mc.capabilities&clientSessionTrack == 0 {
		return nil
	}

	// warning count [2 bytes]
	if len(data) < pos+2 {
		// Tolerate packets that end right after the status flags.
		return nil
	}
	pos += 2

	if mc.status&statusSessionStateChanged == 0 {
		return nil
	}

	// info [length encoded string]
	n, err := skipLengthEncodedString(data[pos:])
	if err != nil {
		return ErrMalformPkt
	}
	pos += n

	// session state changes [length encoded string]
	if pos >= len(data) {
		return ErrMalformPkt
	}
	changes, _, _, err := readLengthEncodedString(data[pos:])
	if err != nil {
		return ErrMalformPkt
	}
	return mc.parseSessionStateChanges(changes)
}

// parseSessionStateChanges decodes the session_state_info block of an OK
// packet and stages the changes on the connection. Unknown block types are
// length-delimited and skipped; truncated blocks are reported as malformed
// packets so that lengths never silently misalign.
func (mc *mysqlConn) parseSessionStateChanges(data []byte) error {
	for len(data) > 0 {
		trackType := SessionTrackType(data[0])
		data = data[1:]
		if len(data) == 0 {
			return ErrMalformPkt
		}
		payload, _, n, err := readLengthEncodedString(data)
		if err != nil {
			return ErrMalformPkt
		}
		data = data[n:]

		change := SessionStateChange{Type: trackType}
		switch trackType {
		case SessionTrackSystemVariables:
			if len(payload) == 0 {
				return ErrMalformPkt
			}
			name, _, n, err := readLengthEncodedString(payload)
			if err != nil {
				return ErrMalformPkt
			}
			if n >= len(payload) {
				return ErrMalformPkt
			}
			value, _, _, err := readLengthEncodedString(payload[n:])
			if err != nil {
				return ErrMalformPkt
			}
			change.Name = string(name)
			change.Value = string(value)

		case SessionTrackSchema,
			SessionTrackStateChange,
			SessionTrackGTIDs,
			SessionTrackTransactionCharacteristics,
			SessionTrackTransactionState:
			if len(payload) == 0 {
				return ErrMalformPkt
			}
			value, _, _, err := readLengthEncodedString(payload)
			if err != nil {
				return ErrMalformPkt
			}
			change.Value = string(value)

		default:
			// Unknown block types are skipped using their declared length.
			continue
		}
		mc.pendingSessionState = append(mc.pendingSessionState, change)
	}
	return nil
}

// commitSessionState publishes the staged session state changes. It must only
// be called once the corresponding command has fully completed, i.e. its
// final OK packet (no more results pending) has been read. This ensures that
// trailing state of a result set is never attributed to the next command
// while its rows are still being read.
func (mc *mysqlConn) commitSessionState() {
	if len(mc.pendingSessionState) == 0 {
		return
	}
	changes := mc.pendingSessionState
	mc.pendingSessionState = nil

	for _, change := range changes {
		switch change.Type {
		case SessionTrackSchema:
			mc.sessionState.Schema = change.Value
		case SessionTrackSystemVariables:
			if mc.sessionState.SystemVars == nil {
				mc.sessionState.SystemVars = make(map[string]string)
			}
			mc.sessionState.SystemVars[change.Name] = change.Value
		case SessionTrackGTIDs:
			mc.sessionState.GTIDs = append(mc.sessionState.GTIDs, change.Value)
		}
	}

	if cb := mc.cfg.sessionStateCallback; cb != nil {
		cb(changes)
	}
}
