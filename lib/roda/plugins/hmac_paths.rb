# frozen-string-literal: true

require 'openssl'
require 'base64'

#
class Roda
  module RodaPlugins
    # The hmac_paths plugin allows protection of paths using an HMAC.  This can be used
    # to prevent users enumerating paths, since only paths with valid HMACs will be
    # respected.
    #
    # To use the plugin, you must provide a +secret+ option.  This sets the secret for
    # the HMACs.  Make sure to keep this value secret, as this plugin does not provide
    # protection against users who know the secret value.  The secret must be at least
    # 32 bytes.
    #
    #   plugin :hmac_paths, secret: 'some-secret-value-with-at-least-32-bytes'
    #
    # To generate a valid HMAC path, you call the +hmac_path+ method:
    #
    #   hmac_path('/widget/1')
    #   # => "/0c2feaefdfc80cc73da19b060c713d4193c57022815238c6657ce2d99b5925eb/0/widget/1"
    #
    # The first segment in the returned path is the HMAC.  The second segment is flags for
    # the type of paths (see below), and the rest of the path is as given.
    #
    # To protect a path or any subsection in the routing tree, you wrap the related code
    # in an +r.hmac_path+ block.
    #
    #   route do |r|
    #     r.hmac_path do
    #       r.get 'widget', Integer do |widget_id|
    #         # ...
    #       end
    #     end
    #   end
    #
    # If first segment of the remaining path contains a valid HMAC for the rest of the path (considering
    # the flags), then +r.hmac_path+ will match and yield to the block, and routing continues inside
    # the block with the HMAC and flags segments removed.
    #
    # In the above example, if you provide a user a link for widget with ID 1, there is no way
    # for them to guess the valid path for the widget with ID 2, preventing a user from
    # enumerating widgets, without relying on custom access control.  Users can only access
    # paths that have been generated by the application and provided to them, either directly
    # or indirectly.
    #
    # In the above example, +r.hmac_path+ is used at the root of the routing tree. If you
    # would like to call it below the root of the routing tree, it works correctly, but you
    # must pass +hmac_path+ the +:root+ option specifying where +r.hmac_paths+ will be called from.
    # Consider this example:
    #
    #   route do |r|
    #     r.on 'widget' do
    #       r.hmac_path do
    #         r.get Integer do |widget_id|
    #           # ...
    #         end
    #       end
    #     end
    #
    #     r.on 'foobar' do
    #       r.hmac_path do
    #         r.get Integer do |foobar_id|
    #           # ...
    #         end
    #       end
    #     end
    #   end
    #
    # For security reasons, the hmac_path plugin does not allow an HMAC path designed for
    # widgets to be a valid match in the +r.hmac_path+ call inside the <tt>r.on 'foobar'</tt>
    # block, preventing users who have a valid HMAC for a widget from looking at the page for
    # a foobar with the same ID.  When generating HMAC paths where the matching +r.hmac_path+
    # call is not at the root of the routing tree, you must pass the +:root+ option:
    #
    #   hmac_path('/1', root: '/widget')
    #   # => "/widget/daccafce3ce0df52e5ce774626779eaa7286085fcbde1e4681c74175ff0bbacd/0/1"
    #
    #   hmac_path('/1', root: '/foobar')
    #   # => "/foobar/c5fdaf482771d4f9f38cc13a1b2832929026a4ceb05e98ed6a0cd5a00bf180b7/0/1"
    #
    # Note how the HMAC changes even though the path is the same.
    #
    # In addition to the +:root+ option, there are additional options that further constrain
    # use of the generated paths.
    #
    # The +:method+ option creates a path that can only be called with a certain request
    # method:
    #
    #   hmac_path('/widget/1', method: :get)
    #   # => "/d38c1e634ecf9a3c0ab9d0832555b035d91b35069efcbf2670b0dfefd4b62fdd/m/widget/1"
    #
    # Note how this results in a different HMAC than the original <tt>hmac_path('/widget/1')</tt>
    # call.  This sets the flags segment to +m+, which means +r.hmac_path+ will consider the
    # request mehod when checking the HMAC, and will only match if the provided request method
    # is GET.  This allows you to provide a user the ability to submit a GET request for the
    # underlying path, without providing them the ability to submit a POST request for the
    # underlying path, with no other access control.
    #
    # The +:params+ option accepts a hash of params, converts it into a query string, and
    # includes the query string in the returned path.  It sets the flags segment to +p+, which
    # means +r.hmac_path+ will check for that exact query string.  Requests with an empty query
    # string or a different string will not match.
    #
    #   hmac_path('/widget/1', params: {foo: 'bar'})
    #   # => "/fe8d03f9572d5af6c2866295bd3c12c2ea11d290b1cbd016c3b68ee36a678139/p/widget/1?foo=bar"
    #
    # For GET requests, which cannot have request bodies, that is sufficient to ensure that the
    # submitted params are exactly as specified. However, POST requests can have request bodies,
    # and request body params override query string params in +r.params+.  So if you are using
    # this for POST requests (or other HTTP verbs that can have request bodies), use +r.GET+
    # instead of +r.params+ to specifically check query string parameters.
    #
    # The generated paths can be timestamped, so that they are only valid until a given time
    # or for a given number of seconds after they are generated, using the :until or :seconds
    # options:
    #
    #   hmac_path('/widget/1', until: Time.utc(2100))
    #   # =>  "/dc8b6e56e4cbe7815df7880d42f0e02956b2e4c49881b6060ceb0e49745a540d/t/4102444800/widget/1"
    #
    #   hmac_path('/widget/1', seconds: Time.utc(2100).to_i - Time.now.to_i)
    #   # =>  "/dc8b6e56e4cbe7815df7880d42f0e02956b2e4c49881b6060ceb0e49745a540d/t/4102444800/widget/1"
    #
    # The :namespace option, if provided, should be a string, and it modifies the generated HMACs
    # to only match those in the same namespace.  This can be used to provide different paths to
    # different users or groups of users.
    #
    #   hmac_path('/widget/1', namespace: '1')
    #   # => "/3793ac2a72ea399c40cbd63f154d19f0fe34cdf8d347772134c506a0b756d590/n/widget/1"
    #
    #   hmac_path('/widget/1', namespace: '2')
    #   # => "/0e1e748860d4fd17fe9b7c8259b1e26996502c38e465f802c2c9a0a13000087c/n/widget/1"
    #
    # The +r.hmac_path+ method accepts a :namespace option, and if a :namespace option is
    # provided, it will only match an hmac path if the namespace given matches the one used
    # when the hmac path was created.
    #
    #   r.hmac_path(namespace: '1'){}
    #   # will match "/3793ac2a72ea399c40cbd63f154d19f0fe34cdf8d347772134c506a0b756d590/n/widget/1"
    #   # will not match "/0e1e748860d4fd17fe9b7c8259b1e26996502c38e465f802c2c9a0a13000087c/n/widget/1"
    #
    # The most common use of the :namespace option is to reference session values, so the value of
    # each path depends on the logged in user.  You can use the +:namespace_session_key+ plugin
    # option to set the default namespace for both +hmac_path+ and +r.hmac_path+:
    #
    #   plugin :hmac_paths, secret: 'some-secret-value-with-at-least-32-bytes',
    #                       namespace_session_key: 'account_id'
    #
    # This will use <tt>session['account_id']</tt> as the default namespace for both +hmac_path+
    # and +r.hmac_path+ (if the session value is not nil, it is converted to a string using +to_s+).
    # You can override the default namespace by passing a +:namespace+ option when calling +hmac_path+
    # and +r.hmac_path+.
    #
    # You can use +:root+, +:method+, +:params+, and +:namespace+ at the same time:
    #
    #   hmac_path('/1', root: '/widget', method: :get, params: {foo: 'bar'}, namespace: '1')
    #   # => "/widget/c14c78a81d34d766cf334a3ddbb7a6b231bc2092ef50a77ded0028586027b14e/mpn/1?foo=bar"
    #
    # This gives you a path only valid for a GET request with a root of <tt>/widget</tt> and
    # a query string of <tt>foo=bar</tt>, using namespace +1+.
    #
    # To handle secret rotation, you can provide an +:old_secret+ option when loading the
    # plugin.
    #
    #   plugin :hmac_paths, secret: 'some-secret-value-with-at-least-32-bytes',
    #                       old_secret: 'previous-secret-value-with-at-least-32-bytes'
    #
    # This will use +:secret+ for constructing new paths, but will respect paths generated by
    # +:old_secret+.
    #
    # = Authorization Chains (Narrower Sub-Links)
    #
    # In addition to single HMAC paths, the plugin supports explicit authorization chains,
    # where a server side issuer signs a parent authorization and then derives strictly
    # narrower child authorizations from it, one level at a time.  This lets you turn a broad
    # parent link (for a whole subtree, any method, long lived) into a narrow sub-link (one
    # sub path, GET only, short lived) without exposing the broad link.
    #
    # The chain is created with the +hmac_authorize+ method, which returns an
    # Roda::RodaPlugins::HmacPaths::HmacAuthorization object:
    #
    #   parent = hmac_authorize('/files', until: Time.utc(2100))
    #
    # You then call +delegate+ on it to derive a narrower level.  Each level is signed with a
    # key derived from its parent, so the verifier can check the integrity of the entire chain:
    #
    #   read_only = parent.delegate('/files/reports', method: :get, until: Time.utc(2099))
    #   one_report = read_only.delegate('/files/reports/2026', method: :get, seconds: 3600)
    #
    # +delegate+ accepts the same +:method+, +:params+, +:seconds+, and +:until+ options as
    # +hmac_authorize+.  A sub-authorization can never widen any parent condition:
    #
    # * its path prefix must be inside the parent path prefix, up to path segment boundaries
    #   (so +/files/reports+ can be narrowed to +/files/reports/2026+, but not to
    #   +/files/secret+ or the prefix lookalike +/files/reports2+)
    # * its request method must stay the same, if a parent level restricted the method (you
    #   cannot remove a GET only restriction)
    # * its expiry must be no later than the parent expiry, if a parent level expired (you
    #   cannot extend the validity period)
    # * its exact query must stay the same, if a parent level restricted the query
    #
    # Attempting any of these widening operations raises a RodaError at issue time, and the
    # verifier independently rejects a chain whose levels are not strictly nested, even if the
    # signed bytes were forged.
    #
    # Turn an authorization into a requestable path with +to_path+.  It defaults to the
    # effective path prefix, but can target any path inside it:
    #
    #   one_report.to_path
    #   # => "/hc1<...chain...>/files/reports/2026"
    #
    #   one_report.to_path('/files/reports/2026/q1.pdf')
    #   # => "/hc1<...chain...>/files/reports/2026/q1.pdf"
    #
    # The resulting path is verified by the same +r.hmac_path+ block used for single HMAC
    # paths.  The +hc1+ segment carries the whole chain, so no router change is needed:
    #
    #   r.hmac_path do
    #     r.get 'files', String do |name|
    #       # Only reached if every level of the chain is intact and the request
    #       # satisfies the intersection of all levels' conditions.
    #     end
    #   end
    #
    # The verifier enforces, for every level in the chain, that the request path is inside the
    # level's path prefix, the request method matches, the exact query string matches, and the
    # current time is before the level's expiry.  Cutting levels off the chain, reordering
    # them, or tampering with any byte invalidates the final signature, so a holder of a
    # narrow link cannot recover a broader parent link.
    #
    # Path prefixes are compared after canonicalization.  The raw path is split on literal
    # slashes before percent decoding, so an encoded slash (<tt>%2F</tt>) is a single segment
    # name and cannot cross a path segment boundary.  Dot segments are normalized per RFC 3986,
    # and a request that would normalize above the authorized prefix (such as
    # <tt>%2e%2e</tt> traversal) does not match.
    #
    # Namespaces work exactly as for single HMAC paths, and a sub-authorization cannot change
    # the namespace of its parent, preserving the per user or per group identity isolation:
    #
    #   parent = hmac_authorize('/files', namespace: current_user_id)
    #   child  = parent.delegate('/files/reports', namespace: current_user_id, method: :get)
    #
    # The +:root+ option is also supported (for +r.hmac_path+ calls below the routing tree
    # root), and must be the same at each level.
    #
    # The maximum number of levels defaults to 8.  It can be changed with the
    # +:max_chain_length+ plugin option (a positive integer).  Both the issuer and the
    # verifier enforce it, bounding the work spent on a single request.
    #
    #   plugin :hmac_paths, secret: 'some-secret-value-with-at-least-32-bytes',
    #                       max_chain_length: 4
    #
    # = HMAC Construction
    #
    # This describes the internals for how HMACs are constructed based on the options provided
    # to +hmac_path+.  In the examples below:
    #
    # * +HMAC+ is the raw HMAC-SHA256 output (first argument is secret, second is data)
    # * +HMAC_hex+ is the hexidecimal version of +HMAC+
    # * +secret+ is the plugin :secret option
    #
    # The +:secret+ plugin option is never used directly as the HMAC secret.  All HMACs are
    # generated with a root-specific secret.  The root will be the empty if no +:root+ option
    # is given.  The hmac path flags are always included in the hmac calculation, prepended to the
    # path:
    #
    #  r.hmac_path('/1')
    #  HMAC_hex(HMAC_hex(secret, ''), '/0/1')
    # 
    #  r.hmac_path('/1', root: '/2')
    #  HMAC_hex(HMAC_hex(secret, '/2'), '/0/1')
    #
    # The +:method+ option uses an uppercase version of the method prepended to the path. This
    # cannot conflict with the path itself, since paths must start with a slash.
    #
    #  r.hmac_path('/1', method: :get)
    #  HMAC_hex(HMAC_hex(secret, ''), 'GET:/m/1')
    # 
    # The +:params+ option includes the query string for the params in the HMAC:
    #
    #  r.hmac_path('/1', params: {k: 2})
    #  HMAC_hex(HMAC_hex(secret, ''), '/p/1?k=2')
    #
    # The +:until+ and +:seconds+ option include the timestamp in the HMAC:
    #
    #  r.hmac_path('/1', until: Time.utc(2100))
    #  HMAC_hex(HMAC_hex(secret, ''), '/t/4102444800/1')
    #
    # If a +:namespace+ option is provided, the original secret used before the +:root+ option is
    # an HMAC of the +:secret+ plugin option and the given namespace.
    # 
    #  r.hmac_path('/1', namespace: '2')
    #  HMAC_hex(HMAC_hex(HMAC(secret, '2'), ''), '/n/1')
    module HmacPaths
      # Prefix used for URL path segments that carry an authorization chain,
      # instead of a single 64 byte HMAC hex digest.
      CHAIN_PREFIX = "hc1"

      # Version tag for the on the wire chain envelope format.
      CHAIN_VERSION = "1".b

      # Unit separator, used between fields of a single chain level record.
      CHAIN_FIELD_SEPARATOR = "\x1f".b

      # Record separator, used between the levels of a chain.
      CHAIN_RECORD_SEPARATOR = "\x1e".b

      # Domain separation prefixes used when deriving the chain secrets.
      CHAIN_LEVEL_PREFIX = "roda.hmac_paths.chain.level:".b
      CHAIN_SIGN_PREFIX = "roda.hmac_paths.chain.sign:".b

      # Default maximum number of levels in a chain.
      DEFAULT_MAX_CHAIN_LENGTH = 8

      def self.configure(app, opts=OPTS)
        hmac_secret = opts[:secret]
        unless hmac_secret.is_a?(String) && hmac_secret.bytesize >= 32
          raise RodaError, "hmac_paths plugin :secret option must be a string containing at least 32 bytes"
        end

        if hmac_old_secret = opts[:old_secret]
          unless hmac_old_secret.is_a?(String) && hmac_old_secret.bytesize >= 32
            raise RodaError, "hmac_paths plugin :old_secret option must be a string containing at least 32 bytes if present"
          end
        end

        app.opts[:hmac_paths_secret] = hmac_secret
        app.opts[:hmac_paths_old_secret] = hmac_old_secret

        if opts[:namespace_session_key]
          app.opts[:hmac_paths_namespace_session_key] = opts[:namespace_session_key]
        end

        max_chain_length = opts.fetch(:max_chain_length, DEFAULT_MAX_CHAIN_LENGTH)
        unless max_chain_length.is_a?(Integer) && max_chain_length >= 1
          raise RodaError, "hmac_paths plugin :max_chain_length option must be an integer greater than or equal to 1 if present"
        end
        app.opts[:hmac_paths_max_chain_length] = max_chain_length
      end

      # Build the normalized condition hash for the given path prefix and options.
      # The returned condition is used both when signing a chain level and when
      # verifying one.
      def self.hmac_path_chain_condition(path_prefix, opts=OPTS)
        unless path_prefix.is_a?(String) && path_prefix.getbyte(0) == 47
          raise RodaError, "path must be a string starting with /"
        end

        prefix = path_prefix.b
        if prefix.include?(CHAIN_FIELD_SEPARATOR) || prefix.include?(CHAIN_RECORD_SEPARATOR)
          raise RodaError, "path must not contain control characters used by hmac authorization chains"
        end

        segments = hmac_path_chain_segments(path_prefix)
        raise RodaError, "invalid path prefix for hmac authorization chain" unless segments

        condition = {prefix: path_prefix, prefix_segments: segments}

        if method = opts[:method]
          method = method.to_s.upcase
          unless /\A[A-Z]+\z/.match?(method)
            raise RodaError, "hmac authorization :method must be a valid HTTP request method"
          end
          condition[:method] = method
        end

        unless opts[:params].nil?
          query = Rack::Utils.build_query(opts[:params])
          if query.b.include?(CHAIN_FIELD_SEPARATOR) || query.b.include?(CHAIN_RECORD_SEPARATOR)
            raise RodaError, "params must not contain control characters used by hmac authorization chains"
          end
          condition[:query] = query
        end

        if valid_until = opts[:until]
          condition[:until] = valid_until.to_i
        elsif seconds = opts[:seconds]
          condition[:until] = Time.now.to_i + seconds
        end

        condition
      end

      # Serialize a single chain level condition into its signed record, which
      # consists of depth, flags, method, query, expiry, and path prefix, separated
      # by unit separators.
      def self.hmac_path_chain_record(depth, condition)
        flags = String.new
        flags << 'm' if condition[:method]
        flags << 'p' if condition.key?(:query)
        flags << 't' if condition[:until]

        [
          depth.to_s,
          flags,
          condition[:method] || '',
          condition.key?(:query) ? condition[:query] : '',
          condition[:until] ? condition[:until].to_s : '',
          condition[:prefix],
        ].map(&:b).join(CHAIN_FIELD_SEPARATOR)
      end

      # Parse a serialized chain level record into its depth and condition.
      # Returns nil if the record is malformed or the flags do not match the
      # remaining fields.
      def self.hmac_path_chain_parse_record(depth, record)
        fields = record.split(CHAIN_FIELD_SEPARATOR, 6)
        return unless fields.length == 6

        record_depth, flags, method, query, valid_until, prefix = fields
        return unless record_depth == depth.to_s

        has_method = flags.include?('m')
        has_params = flags.include?('p')
        has_expiry = flags.include?('t')
        expected_flags = String.new
        expected_flags << 'm' if has_method
        expected_flags << 'p' if has_params
        expected_flags << 't' if has_expiry
        return unless flags == expected_flags

        return unless has_method == !method.empty?
        return unless !has_method || /\A[A-Z]+\z/.match?(method)
        return unless has_expiry == !valid_until.empty?
        return unless !has_expiry || /\A[0-9]+\z/.match?(valid_until)
        return unless prefix.getbyte(0) == 47

        segments = hmac_path_chain_segments(prefix)
        return unless segments

        condition = {prefix: prefix, prefix_segments: segments}
        condition[:method] = method if has_method
        condition[:query] = query if has_params
        condition[:until] = valid_until.to_i if has_expiry
        condition
      end

      # Return the canonical path segments for a percent-encoded raw path.  The
      # path is split on literal slashes before percent decoding, so an encoded
      # slash (%2F) cannot cross a path segment boundary.  Dot segments are
      # normalized per RFC 3986, and a path that escapes above its root returns
      # nil.
      def self.hmac_path_chain_segments(path)
        raw_segments = path.b.split('/', -1)
        segments = []

        raw_segments.each_with_index do |segment, index|
          next if index == 0
          next if index == raw_segments.length - 1 && segment.empty?
          return if segment.empty?

          decoded = segment.gsub(/(?:%[0-9a-fA-F]{2})+/) do |escaped|
            [escaped.delete('%')].pack('H*')
          end

          case decoded
          when '..'
            return if segments.empty?
            segments.pop
          when '.'
            # Current directory segment, does not add a path level.
          else
            segments << decoded
          end
        end

        segments
      end

      # Whether the target canonical segments are the same as the prefix segments
      # or below them, up to path segment boundaries.  An empty prefix (the root
      # path) contains every path.
      def self.hmac_path_chain_prefix_contains?(prefix_segments, target_segments)
        return false if prefix_segments.nil? || target_segments.nil?
        target_segments.length >= prefix_segments.length &&
          target_segments.first(prefix_segments.length) == prefix_segments
      end

      # Whether the child condition is a subset of the parent condition.  A child
      # can only stay inside the parent path prefix, keep the same request method,
      # keep the same exact query, and expire no later than the parent.
      def self.hmac_path_chain_narrowed?(parent, child)
        return false unless hmac_path_chain_prefix_contains?(parent[:prefix_segments], child[:prefix_segments])
        return false if parent[:method] && child[:method] != parent[:method]
        return false if parent.key?(:query) && (!child.key?(:query) || child[:query] != parent[:query])
        return false if parent[:until] && (!child[:until] || child[:until] > parent[:until])
        true
      end

      # The effective condition at a child level, as the intersection of the
      # effective parent condition and the child condition.
      def self.hmac_path_chain_intersection(parent, child)
        condition = {prefix: child[:prefix], prefix_segments: child[:prefix_segments]}
        condition[:method] = child[:method] || parent[:method]
        if child.key?(:query)
          condition[:query] = child[:query]
        elsif parent.key?(:query)
          condition[:query] = parent[:query]
        end
        expiry = [parent[:until], child[:until]].compact.min
        condition[:until] = expiry if expiry
        condition
      end

      # Derive the root specific hex secret for a chain or a plain hmac_path,
      # using the plugin secret, optional namespace, and root path.
      def self.hmac_path_chain_root_secret(secret, namespace, root)
        if namespace
          secret = OpenSSL::HMAC.digest(OpenSSL::Digest::SHA256.new, secret, namespace)
        end
        OpenSSL::HMAC.hexdigest(OpenSSL::Digest::SHA256.new, secret, root)
      end

      # URL safe base64 encoding without line feeds.
      def self.hmac_path_chain_base64(data)
        Base64.urlsafe_encode64(data.b)
      end

      # Decode URL safe base64 data, returning nil for malformed or non-canonical
      # input.
      def self.hmac_path_chain_unbase64(data)
        decoded = Base64.urlsafe_decode64(data)
        decoded if hmac_path_chain_base64(decoded) == data
      rescue ArgumentError
        nil
      end

      module ClassMethods
        RodaPlugins.opt_attr_reader(self, :hmac_paths_secret)
        RodaPlugins.opt_attr_reader(self, :hmac_paths_old_secret)
        RodaPlugins.opt_attr_reader(self, :hmac_paths_namespace_session_key)
        RodaPlugins.opt_attr_reader(self, :hmac_paths_max_chain_length)
      end

      module InstanceMethods
        # Return a path with an HMAC.  Designed to be used with r.hmac_path, to make sure
        # users can only request paths that they have been provided by the application
        # (directly or indirectly).  This can prevent users of a site from enumerating
        # valid paths.  The given path should be a string starting with +/+.  Options:
        #
        # :method :: Limits the returned path to only be valid for the given request method.
        # :namespace :: Make the HMAC value depend on the given namespace. If this is not
        #               provided, the default namespace is used.  To explicitly not use a
        #               namespace when there is a default namespace, pass a nil value.
        # :params :: Includes parameters in the query string of the returned path, and
        #            limits the returned path to only be valid for that exact query string.
        # :root :: Should be an empty string or string starting with +/+. This will be
        #          the already matched path of the routing tree using r.hmac_path. Defaults
        #          to the empty string, which will returns paths valid for r.hmac_path at
        #          the top level of the routing tree.
        # :seconds :: Make the given path valid for the given integer number of seconds.
        # :until :: Make the given path valid until the given Time.
        def hmac_path(path, opts=OPTS)
          unless path.is_a?(String) && path.getbyte(0) == 47
            raise RodaError, "path must be a string starting with /"
          end

          root = opts[:root] || ''
          unless root.is_a?(String) && ((root_byte = root.getbyte(0)) == 47 || root_byte == nil)
            raise RodaError, "root must be empty string or string starting with /"
          end

          if valid_until = opts[:until]
            valid_until = valid_until.to_i
          elsif seconds = opts[:seconds]
            valid_until = Time.now.to_i + seconds
          end

          flags = String.new
          path = path.dup

          if method = opts[:method]
            flags << 'm'
          end

          if params = opts[:params]
            flags << 'p'
            path << '?' << Rack::Utils.build_query(params)
          end

          if hmac_path_namespace(opts)
            flags << 'n'
          end

          if valid_until
            flags << 't'
            path = "/#{valid_until}#{path}"
          end

          flags << '0' if flags.empty?
          
          hmac_path = if method
            "#{method.to_s.upcase}:/#{flags}#{path}"
          else
            "/#{flags}#{path}"
          end

          "#{root}/#{hmac_path_hmac(root, hmac_path, opts)}/#{flags}#{path}"
        end

        # The HMAC to use in hmac_path, for the given root, path, and options.
        def hmac_path_hmac(root, path, opts=OPTS)
          OpenSSL::HMAC.hexdigest(OpenSSL::Digest::SHA256.new, hmac_path_hmac_secret(root, opts), path)
        end

        # Return the root of an authorization chain for the given path prefix.  The
        # returned HmacAuthorization can be narrowed using HmacAuthorization#delegate,
        # and turned into a requestable URL path using HmacAuthorization#to_path.
        #
        # The given +path_prefix+ should be a string starting with +/+.  It authorizes
        # access to that path prefix (the path itself and any paths below it, up to
        # path segment boundaries).  Options:
        #
        # :method :: Only allow the given request method (e.g. <tt>:get</tt>).
        # :namespace :: Make the chain depend on the given namespace, preserving the
        #               namespace isolation used by hmac_path. If this is not provided,
        #               the default namespace is used.  Pass nil to explicitly not use
        #               a namespace when there is a default namespace.
        # :params :: Only allow requests with the exact given query parameters.
        # :root :: Should be an empty string or string starting with +/+.  This is the
        #          already matched path of the routing tree where r.hmac_path will be
        #          called.  Defaults to the empty string.
        # :seconds :: Make the chain valid for the given integer number of seconds.
        # :until :: Make the chain valid until the given Time.
        def hmac_authorize(path_prefix, opts=OPTS)
          root = opts[:root] || ''
          unless root.is_a?(String) && ((root_byte = root.getbyte(0)) == 47 || root_byte == nil)
            raise RodaError, "root must be empty string or string starting with /"
          end

          HmacAuthorization.new(self, opts[:root] || '', opts,
            HmacPaths.hmac_path_chain_condition(path_prefix, opts))
        end

        # The binary chain key at the root of an authorization chain, for the given
        # root path and options.  Domain separated from the plain hmac_path secrets
        # so a chain signature can never be accepted as a plain hmac_path HMAC.
        def hmac_path_chain_secret(root, opts=OPTS)
          root_secret = HmacPaths.hmac_path_chain_root_secret(opts[:secret] || self.class.hmac_paths_secret,
            hmac_path_namespace(opts), root)
          OpenSSL::HMAC.digest(OpenSSL::Digest::SHA256.new, root_secret, CHAIN_LEVEL_PREFIX + root.b)
        end

        # The namespace to use for the hmac path.  If a :namespace option is not
        # provided, and a :namespace_session_key option was provided, this will
        # use the value of the related session key, if present.
        def hmac_path_namespace(opts=OPTS)
          opts.fetch(:namespace){hmac_path_default_namespace}
        end

        private

        # The secret used to calculate the HMAC in hmac_path. This is itself an HMAC, created
        # using the secret given in the plugin, for the given root and options.
        # This always returns a hexidecimal string.
        def hmac_path_hmac_secret(root, opts=OPTS)
          HmacPaths.hmac_path_chain_root_secret(opts[:secret] || self.class.hmac_paths_secret,
            hmac_path_namespace(opts), root)
        end

        # The default namespace to use for hmac_path, if a :namespace option is not provided.
        def hmac_path_default_namespace
          if (key = self.class.hmac_paths_namespace_session_key) && (value = session[key])
            value.to_s
          end
        end
      end

      # A single level in an authorization chain, created using hmac_authorize or
      # HmacAuthorization#delegate.  Instances should not be created directly.
      class HmacAuthorization
        # The application instance (scope) that created this level.
        attr_reader :scope

        # The already matched path of the routing tree where r.hmac_path is called.
        attr_reader :root

        # The options used for this level (:namespace and :secret related).
        attr_reader :opts

        # The most recently derived chain key, as a binary string.
        attr_reader :key

        # The signed records for all levels from the root to this level.
        attr_reader :records

        # The effective conditions at this level, as the intersection of all
        # conditions from the root to this level.
        attr_reader :condition

        # The number of levels in the chain, starting at 1 for the root level.
        attr_reader :depth

        def initialize(scope, root, opts, condition, key=nil, records=nil, depth=1, namespace=nil)
          @scope = scope
          @root = root
          @opts = opts
          if key
            @key = key
            @records = records
            @condition = condition
            @depth = depth
            @namespace = namespace
          else
            @namespace = scope.hmac_path_namespace(opts)
            @depth = 1
            record = HmacPaths.hmac_path_chain_record(@depth, condition)
            @records = [record]
            @key = OpenSSL::HMAC.digest(OpenSSL::Digest::SHA256.new,
              scope.hmac_path_chain_secret(root, opts.merge(namespace: @namespace)), record)
            @condition = condition
          end
        end

        # Derive a narrower child authorization from this level, and return the
        # new HmacAuthorization.  The child conditions must be a subset of this
        # level's conditions, it is never possible to widen any parent condition:
        #
        # * the child path prefix must be inside the parent path prefix, up to
        #   path segment boundaries
        # * the child request method must match the parent request method, if
        #   the parent level restricted the method
        # * the child expiry must not be later than the parent expiry, if the
        #   parent level had an expiry
        # * the child exact query must match the parent exact query, if the
        #   parent level restricted the query
        #
        # Accepts the same :method, :params, :seconds, and :until options as
        # hmac_authorize.  Raises RodaError if the child would widen any parent
        # condition, or if the maximum chain length would be exceeded.
        def delegate(path_prefix, sub_opts=OPTS)
          if @depth >= scope.class.hmac_paths_max_chain_length
            raise RodaError, "hmac authorization chain exceeds maximum length of #{scope.class.hmac_paths_max_chain_length}"
          end

          if sub_opts.key?(:namespace) && scope.hmac_path_namespace(sub_opts) != @namespace
            raise RodaError, "hmac sub-authorization cannot change the namespace of a parent authorization"
          end

          sub_root = sub_opts.fetch(:root, @root)
          valid_root = sub_root.is_a?(String) &&
            ((root_byte = sub_root.getbyte(0)) == 47 || root_byte == nil) &&
            sub_root == @root
          unless valid_root
            raise RodaError, "hmac sub-authorization cannot change the root of a parent authorization"
          end

          sub_condition = HmacPaths.hmac_path_chain_condition(path_prefix, sub_opts)
          unless HmacPaths.hmac_path_chain_narrowed?(condition, sub_condition)
            raise RodaError, "hmac sub-authorization must not widen any parent authorization condition"
          end

          depth = @depth + 1
          record = HmacPaths.hmac_path_chain_record(depth, sub_condition)
          sub_key = OpenSSL::HMAC.digest(OpenSSL::Digest::SHA256.new, @key, record.b)
          records = @records.dup
          records << record

          self.class.new(@scope, @root, @opts,
            HmacPaths.hmac_path_chain_intersection(condition, sub_condition),
            sub_key, records, depth, @namespace)
        end

        # Return a requestable URL path for this authorization.  The path of the
        # returned URL defaults to the effective path prefix, but a more specific
        # target path inside the prefix can be given.  The target must be inside
        # the effective path prefix, up to path segment boundaries.
        def to_path(target_path = condition[:prefix])
          target_segments = HmacPaths.hmac_path_chain_segments(target_path)
          unless HmacPaths.hmac_path_chain_prefix_contains?(condition[:prefix_segments], target_segments)
            raise RodaError, "hmac authorization target path must be inside the authorized path prefix"
          end

          global_flags = @namespace ? 'n' : ''
          global = global_flags.b
          encoded_records = @records.map do |record|
            HmacPaths.hmac_path_chain_base64(record)
          end

          signature = OpenSSL::HMAC.hexdigest(OpenSSL::Digest::SHA256.new,
            @key, HmacPaths::CHAIN_SIGN_PREFIX)

          fields = [HmacPaths::CHAIN_VERSION, global, depth.to_s.b, signature.b]
          fields.concat(encoded_records)

          envelope = HmacPaths.hmac_path_chain_base64(fields.join(HmacPaths::CHAIN_RECORD_SEPARATOR))
          chain_segment = HmacPaths::CHAIN_PREFIX + envelope

          target_suffix = target_path == '/' ? '' : target_path
          root + "/" + chain_segment + target_suffix
        end
      end

      module RequestMethods
        # Looks at the first segment of the remaining path, and if it contains a valid HMAC for the
        # rest of the path considering the flags in the second segment and the given options, the
        # block matches and is yielded to, and the result of the block is returned. Otherwise, the
        # block does not matches and routing continues after the call.
        def hmac_path(opts=OPTS, &block)
          orig_path = remaining_path
          mpath = matched_path

          on String do |submitted_hmac|
            rpath = remaining_path

            if submitted_hmac.start_with?(HmacPaths::CHAIN_PREFIX)
              begin
                if hmac_path_chain_valid?(mpath, submitted_hmac, opts)
                  always(&block)
                end
              rescue StandardError
                # Malformed chain segments never match and must not raise.
              end
              @remaining_path = orig_path
              return
            end

            if submitted_hmac.bytesize == 64
              on String do |flags|
                if flags.include?('n') ^ !scope.hmac_path_namespace(opts).nil?
                  # Namespace required and not provided, or provided and not required.
                  # Bail early to avoid unnecessary HMAC calculation.
                  @remaining_path = orig_path
                  return
                end

                if flags.include?('m')
                  rpath = "#{env['REQUEST_METHOD'].to_s.upcase}:#{rpath}"
                end

                if flags.include?('p')
                  rpath = "#{rpath}?#{env["QUERY_STRING"]}"
                end

                if hmac_path_valid?(mpath, rpath, submitted_hmac, opts)
                  if flags.include?('t')
                    on Integer do |int|
                      if int >= Time.now.to_i
                        always(&block)
                      else
                        # Return from method without matching
                        @remaining_path = orig_path
                        return
                      end
                    end
                  else
                    always(&block)
                  end
                end
              end

              # Return from method without matching
              @remaining_path = orig_path
              return
            end

            # Return from method without matching
            @remaining_path = orig_path
            return
          end
        end

        private

        # Validate an authorization chain segment, enforcing the integrity of the
        # whole chain, that each level is a subset of its parent, and that the
        # request satisfies the intersection of all levels' conditions.
        def hmac_path_chain_valid?(root, submitted_segment, opts)
          hmac_path_chain_match_request(root, submitted_segment, opts, nil) ||
            (old_secret = roda_class.hmac_paths_old_secret) &&
            hmac_path_chain_match_request(root, submitted_segment, opts, old_secret)
        end

        # Verify the chain against the current request, using the given secret
        # (the current plugin secret by default).
        def hmac_path_chain_match_request(root, submitted_segment, opts, secret)
          verify_opts = opts
          if secret
            verify_opts = opts.dup
            verify_opts[:secret] = secret
          end

          return unless result = hmac_path_chain_parse(root, submitted_segment, verify_opts)
          _depth, key, conditions, signature = result

          signed_signature = OpenSSL::HMAC.hexdigest(OpenSSL::Digest::SHA256.new,
            key, HmacPaths::CHAIN_SIGN_PREFIX)

          return unless Rack::Utils.secure_compare(signed_signature, signature)

          now = Time.now.to_i
          request_segments = HmacPaths.hmac_path_chain_segments(remaining_path) || []
          request_method = env['REQUEST_METHOD'].to_s.upcase
          request_query = env['QUERY_STRING'].to_s

          conditions.each do |condition|
            return unless HmacPaths.hmac_path_chain_prefix_contains?(condition[:prefix_segments], request_segments)
            return if condition[:method] && condition[:method] != request_method
            return if condition.key?(:query) && condition[:query] != request_query
            return if condition[:until] && condition[:until] < now
          end

          true
        end

        # Parse the chain segment, verify every level is signed by its parent and
        # is a subset of its parent, and return [depth, key, conditions, signature].
        # Returns nil if the chain is malformed, too long, tampered with, or widened.
        def hmac_path_chain_parse(root, submitted_segment, opts)
          envelope = HmacPaths.hmac_path_chain_unbase64(submitted_segment.byteslice(HmacPaths::CHAIN_PREFIX.bytesize..-1))
          return unless envelope

          fields = envelope.split(HmacPaths::CHAIN_RECORD_SEPARATOR, -1)
          return unless fields.length >= 4

          version, global_flags, depth_string, signature, *records = fields
          return unless version == HmacPaths::CHAIN_VERSION

          if global_flags.include?('n') ^ !scope.hmac_path_namespace(opts).nil?
            # Namespace required and not provided, or provided and not required.
            return
          end
          return unless global_flags == (global_flags.include?('n') ? 'n' : '')

          return unless /\A[0-9]+\z/.match?(depth_string)
          depth = depth_string.to_i
          max_depth = roda_class.hmac_paths_max_chain_length
          return if depth < 1 || depth > max_depth
          return unless records.length == depth
          return unless signature.bytesize == 64 && signature =~ /\A[0-9a-f]{64}\z/

          key = scope.hmac_path_chain_secret(root, opts)
          conditions = []

          records.each_with_index do |record, index|
            level = index + 1
            return unless record = HmacPaths.hmac_path_chain_unbase64(record)
            return unless condition = HmacPaths.hmac_path_chain_parse_record(level, record.b)

            if index > 0
              return unless HmacPaths.hmac_path_chain_narrowed?(conditions.last, condition)
            end

            key = OpenSSL::HMAC.digest(OpenSSL::Digest::SHA256.new, key, record)
            conditions << condition
          end

          [depth, key, conditions, signature]
        end

        # Determine whether the provided hmac matches.
        def hmac_path_valid?(root, path, hmac, opts=OPTS)
          if Rack::Utils.secure_compare(scope.hmac_path_hmac(root, path, opts), hmac)
            true
          elsif old_secret = roda_class.hmac_paths_old_secret
            opts = opts.dup
            opts[:secret] = old_secret
            Rack::Utils.secure_compare(scope.hmac_path_hmac(root, path, opts), hmac)
          else
            false
          end
        end
      end
    end

    register_plugin(:hmac_paths, HmacPaths)
  end
