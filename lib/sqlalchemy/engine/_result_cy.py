    @HasMemoized_ro_memoized_attribute
    def _row_getter(
        self,
    ) -> tuple[
        Callable[..., _R] | None,
        Callable[..., Sequence[_R]] | None,
        Callable[..., Sequence[Any]] | None,
    ]:
        """Return a three-tuple of callables
        ``(single_row, many_rows, interim_rows)``.

        ``single_row`` and ``many_rows`` produce :class:`.Row` objects for
        one input row or a sequence of them.  ``interim_rows`` produces
        rows in "interim" form for a sequence of input rows: plain tuples
        with result processors and tuple filters applied but no
        :class:`.Row` construction, falling back to ``many_rows`` when
        Row objects are required (row logging, scalar sources).

        """
        real_result = self if self._real_result is None else self._real_result

        metadata = self._metadata
        tuple_filters = metadata._tuplefilter
        flag: cython.char = _FLAG_SIMPLE

        if real_result._source_supports_scalars:
            if not self._generate_rows:
                return None, None, None
            else:
                flag = _FLAG_SCALAR_TO_TUPLE
        elif tuple_filters is not None:
            flag = _FLAG_TUPLE_FILTER

        processors: tuple
        proc_valid: tuple

        if metadata._effective_processors is not None:
            ep = metadata._effective_processors
            if flag == _FLAG_TUPLE_FILTER:
                ep = tuple_filters(ep)

            processors = tuple(ep)
            proc_valid = tuple(
                [i for i, p in enumerate(processors) if p is not None]
            )
        else:
            processors = ()
            proc_valid = ()

        proc_size: cython.Py_ssize_t = len(processors)
        log_row = real_result._row_logging_fn
        has_log_row: cython.bint = log_row is not None

        key_to_index = metadata._key_to_index
        _Row = Row

        if flag == _FLAG_SIMPLE and proc_size == 0 and not has_log_row:
            # just build the rows

            def single_row_simple(input_row: Sequence[Any], /) -> Row:
                return _Row(metadata, None, key_to_index, input_row)

            if cython.compiled:

                def many_rows_simple(rows: Sequence[Any], /) -> list[Any]:
                    size: cython.Py_hash_t = len(rows)
                    i: cython.Py_ssize_t
                    result: list = PyList_New(size)
                    for i in range(size):
                        row: object = _Row(
                            metadata, None, key_to_index, rows[i]
                        )
                        Py_INCREF(row)
                        PyList_SET_ITEM(result, i, row)
                    return result

            else:

                def many_rows_simple(rows: Sequence[Any], /) -> list[Any]:
                    return [
                        _Row(metadata, None, key_to_index, row) for row in rows
                    ]

            def interim_rows_simple(rows: Sequence[Any], /) -> Sequence[Any]:
                # interim rows must be tuples so that position-based
                # getters and slices apply; most DBAPIs return tuples
                # already
                if rows and type(rows[0]) is not tuple:
                    return [tuple(row) for row in rows]
                return rows

            return single_row_simple, many_rows_simple, interim_rows_simple  # type: ignore[return-value] # noqa: E501

        first_row: cython.bint = True

        def single_row(input_row: Sequence[Any], /) -> Row:
            nonlocal first_row

            if flag == _FLAG_SCALAR_TO_TUPLE:
                input_row = (input_row,)
            elif flag == _FLAG_TUPLE_FILTER:
                input_row = tuple_filters(input_row)

            if proc_size != 0:
                if first_row:
                    first_row = False
                    assert len(input_row) == proc_size
                input_row = _apply_processors(
                    processors, proc_size, proc_valid, input_row
                )

            row: Row = _Row(metadata, None, key_to_index, input_row)
            if has_log_row:
                row = log_row(row)
            return row

        many_rows = _list_map(single_row)

        if flag == _FLAG_SCALAR_TO_TUPLE or has_log_row:
            # scalar-source rows have no tuple form; row logging requires
            # the Row objects themselves
            interim_rows = many_rows
        else:

            def single_interim_row(input_row: Sequence[Any], /) -> Any:
                if flag == _FLAG_TUPLE_FILTER:
                    input_row = tuple_filters(input_row)
                if proc_size != 0:
                    input_row = _apply_processors(
                        processors, proc_size, proc_valid, input_row
                    )
                elif type(input_row) is not tuple:
                    input_row = tuple(input_row)
                return input_row

            interim_rows = _list_map(single_interim_row)

        return single_row, many_rows, interim_rows  # type: ignore[return-value] # noqa: E501

    @HasMemoized_ro_memoized_attribute
    def _iterator_getter(self) -> Callable[[Self], Iterator[_R]]:
        make_row = self._row_getter[0]

        post_creational_filter = self._post_creational_filter

        if self._unique_filter_state is not None:
            uniques: set
            uniques, strategy = self._unique_strategy

            def iterrows(self: Self) -> Iterator[_R]:
                for raw_row in self._fetchiter_impl():
                    row = (
                        make_row(raw_row) if make_row is not None else raw_row
                    )
                    hashed = strategy(row) if strategy is not None else row
                    if hashed in uniques:
                        continue
                    uniques.add(hashed)
                    if post_creational_filter is not None:
                        row = post_creational_filter(row)
                    yield row

        else:

            def iterrows(self: Self) -> Iterator[_R]:
                for raw_row in self._fetchiter_impl():
                    row = (
                        make_row(raw_row) if make_row is not None else raw_row
                    )
                    if post_creational_filter is not None:
                        row = post_creational_filter(row)
                    yield row

        return iterrows

    def _raw_all_tuples(self) -> Sequence[tuple[Any, ...]]:
        """Return all remaining rows as plain processed tuples, as produced
        by the ``interim_rows`` element of :attr:`._row_getter`;
        :class:`.Row` objects are produced instead where required (row
        logging, scalar sources).

        Used by ORM loading, whose row getters are position-based and
        accept any tuple-like row.

        Uniquing and post-creational filters are not applied here, so
        may not be present on the :class:`.Result` when this method is
        used.

        """
        assert self._unique_filter_state is None
        assert self._post_creational_filter is None
        interim_rows = self._row_getter[2]
        assert interim_rows is not None
        rows = self._fetchall_impl()
        return interim_rows(rows)

    def _allrows(self) -> Sequence[_R]:
        post_creational_filter = self._post_creational_filter

        make_rows = self._row_getter[1]

        rows = self._fetchall_impl()
        made_rows: Sequence[_InterimRowType[_R]]
        if make_rows is not None:
            made_rows = make_rows(rows)
        else:
            made_rows = rows

        interim_rows: Sequence[_R]

        if self._unique_filter_state is not None:
            uniques: set
            uniques, strategy = self._unique_strategy
            interim_rows = _apply_unique_strategy(
                made_rows, [], uniques, strategy
            )
        else:
            interim_rows = made_rows  # type: ignore[assignment]

        if post_creational_filter is not None:
            interim_rows = [
                post_creational_filter(row) for row in interim_rows
            ]
        return interim_rows

    @HasMemoized_ro_memoized_attribute
    def _onerow_getter(
        self,
    ) -> Callable[[Self], Literal[_NoRow._NO_ROW] | _R]:
        make_row = self._row_getter[0]

        post_creational_filter = self._post_creational_filter

        if self._unique_filter_state is not None:
            uniques: set
            uniques, strategy = self._unique_strategy

            def onerow(self: Self) -> Literal[_NoRow._NO_ROW] | _R:
                while True:
                    row = self._fetchone_impl()
                    if row is None:
                        return _NO_ROW
                    else:
                        obj: _InterimRowType[Any] = (
                            make_row(row) if make_row is not None else row
                        )
                        hashed = strategy(obj) if strategy is not None else obj
                        if hashed in uniques:
                            continue
                        uniques.add(hashed)
                        if post_creational_filter is not None:
                            obj = post_creational_filter(obj)
                        return obj  # type: ignore[return-value]

        else:

            def onerow(self: Self) -> Literal[_NoRow._NO_ROW] | _R:
                row = self._fetchone_impl()
                if row is None:
                    return _NO_ROW
                else:
                    interim_row: _InterimRowType[Any] = (
                        make_row(row) if make_row is not None else row
                    )
                    if post_creational_filter is not None:
                        interim_row = post_creational_filter(interim_row)
                    return interim_row  # type: ignore[return-value]

        return onerow

    @HasMemoized_ro_memoized_attribute
    def _manyrow_getter(self) -> Callable[[Self, int | None], Sequence[_R]]:
        make_rows = self._row_getter[1]
        real_result = self if self._real_result is None else self._real_result
        yield_per = real_result._yield_per

        post_creational_filter = self._post_creational_filter

        if self._unique_filter_state:
            uniques: set
            uniques, strategy = self._unique_strategy

            def manyrows(self: Self, num: int | None, /) -> Sequence[_R]:
                made_rows: Sequence[Any]
                collect: list[_R] = []

                _manyrows = self._fetchmany_impl

                if num is None:
                    # if None is passed, we don't know the default
                    # manyrows number, DBAPI has this as cursor.arraysize
                    # different DBAPIs / fetch strategies may be different.
                    # do a fetch to find what the number is.  if there are
                    # only fewer rows left, then it doesn't matter.
                    if yield_per:
                        num_required = num = yield_per
                    else:
                        rows = _manyrows()
                        num = len(rows)
                        made_rows = (
                            rows if make_rows is None else make_rows(rows)
                        )
                        _apply_unique_strategy(
                            made_rows, collect, uniques, strategy
                        )
                        num_required = num - len(collect)
                else:
                    num_required = num

                assert num is not None

                while num_required:
                    rows = _manyrows(num_required)
                    if not rows:
                        break

                    made_rows = rows if make_rows is None else make_rows(rows)
                    _apply_unique_strategy(
                        made_rows, collect, uniques, strategy
                    )
                    num_required = num - len(collect)

                if post_creational_filter is not None:
                    collect = [post_creational_filter(row) for row in collect]
                return collect

        else:

            def manyrows(self: Self, num: int | None, /) -> Sequence[_R]:
                if num is None:
                    num = yield_per

                rows: Sequence = self._fetchmany_impl(num)
                if make_rows is not None:
                    rows = make_rows(rows)
                if post_creational_filter is not None:
                    rows = [post_creational_filter(row) for row in rows]
                return rows

        return manyrows

