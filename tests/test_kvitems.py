"""Tests for the ijson.kvitems method"""

from .test_base import ARRAY_JSON, EMPTY_MEMBER_TEST_CASES, JSON, JSON_KVITEMS, JSON_KVITEMS_META, JSON_OBJECT

import sys

import pytest

import ijson
from ijson import DuplicateKeyError, DuplicateKeyPolicy


DUPLICATE_JSON = (
    b'{"o": {"m": 1, "m": 2, "inner": {"m": 3, "m": 4}}, '
    b'"arr": [{"z": 1, "z": 2}, {"z": 7}]}'
)


def test_kvitems_duplicate_keys_keep_last_is_default(adaptor):
    result = adaptor.kvitems(DUPLICATE_JSON, "o")
    assert result == [("m", 1), ("m", 2), ("inner", {"m": 4})]


@pytest.mark.parametrize("policy", [DuplicateKeyPolicy.KEEP_FIRST, "keep_first"])
def test_kvitems_duplicate_keys_keep_first(adaptor, policy):
    assert adaptor.kvitems(DUPLICATE_JSON, "o", duplicate_keys=policy) == [
        ("m", 1),
        ("inner", {"m": 3}),
    ]


def test_kvitems_duplicate_keys_array_objects_independent(adaptor):
    assert adaptor.kvitems(
        DUPLICATE_JSON, "arr.item", duplicate_keys=DuplicateKeyPolicy.KEEP_FIRST
    ) == [("z", 1), ("z", 7)]


@pytest.mark.parametrize("policy", [DuplicateKeyPolicy.REJECT, "reject"])
def test_kvitems_duplicate_keys_reject(adaptor, policy):
    with pytest.raises(DuplicateKeyError):
        adaptor.kvitems(DUPLICATE_JSON, "o", duplicate_keys=policy)


def test_kvitems_duplicate_keys_decoded_key(adaptor):
    json = b'{"o": {"a": 1, "\\u0061": 2}}'
    assert adaptor.kvitems(json, "o", duplicate_keys=DuplicateKeyPolicy.KEEP_FIRST) == [("a", 1)]
    with pytest.raises(DuplicateKeyError):
        adaptor.kvitems(json, "o", duplicate_keys=DuplicateKeyPolicy.REJECT)


def test_kvitems_keep_first_validates_ignored_value(adaptor):
    bad_json = b'{"o": {"m": 1, "m": [1, 2,]}}'
    with pytest.raises(ijson.JSONError):
        adaptor.kvitems(bad_json, "o", duplicate_keys=DuplicateKeyPolicy.KEEP_FIRST)


def test_kvitems_duplicate_inside_value(adaptor):
    json = b'{"o": {"v": {"k": 1, "k": 2}}}'
    assert adaptor.kvitems(json, "o", duplicate_keys=DuplicateKeyPolicy.KEEP_FIRST) == [
        ("v", {"k": 1})
    ]

def test_kvitems(adaptor):
    assert JSON_KVITEMS == adaptor.kvitems(JSON, 'docs.item')


def test_kvitems_toplevel(adaptor):
    kvitems = adaptor.kvitems(JSON, '')
    assert 1 == len(kvitems)
    key, value = kvitems[0]
    assert 'docs' == key
    assert JSON_OBJECT['docs'] == value


def test_kvitems_empty(adaptor):
    assert [] == adaptor.kvitems(JSON, 'docs')


def test_kvitems_twodictlevels(adaptor):
    json = b'{"meta":{"view":{"columns":[{"id": -1}, {"id": -2}]}}}'
    view = adaptor.kvitems(json, 'meta.view')
    assert 1 == len(view)
    key, value = view[0]
    assert 'columns' == key
    assert [{'id': -1}, {'id': -2}] == value


def test_kvitems_different_underlying_types(adaptor):
    assert JSON_KVITEMS_META == adaptor.kvitems(JSON, 'docs.item.meta')


def test_kvitems_array(adaptor):
    assert JSON_KVITEMS == adaptor.kvitems(ARRAY_JSON, 'item.docs.item')


@pytest.mark.parametrize("test_case", [
    pytest.param(value, id=name) for name, value in EMPTY_MEMBER_TEST_CASES.items()
])
def test_kvitems_empty_member(adaptor, test_case):
    assert test_case.kvitems == adaptor.kvitems(test_case.json, test_case.prefix)


def test_coro_needs_input_with_three_elements(backend):
    int_element_parse_events = list(backend.parse(b'{"a": 0}'))
    # all good
    assert [('a', 0)] == list(backend.kvitems(int_element_parse_events, ''))
    # one more element in event
    with pytest.raises(ValueError, match="too many values"):
        next(backend.kvitems((event + ('extra dummy',) for event in int_element_parse_events), ''))
    # one less
    with pytest.raises(ValueError, match="not enough values"):
        next(backend.kvitems((event[:-1] for event in int_element_parse_events), ''))
    # not an iterable
    with pytest.raises(TypeError, match="cannot unpack"):
        next(backend.kvitems([None], ''))


def test_user_events(backend):
    """
    User-provided events work correct -- yajl2_c used to fail with event names
    that weren't generated by itself.
    """
    int_element_parse_events = [
        ('', 'start_map', None),
        ('', 'map_key', 'a'),
        ('a', 'number', 0),
        ('', 'end_map', None),
    ]
    assert [('a', 0)] == list(backend.kvitems(int_element_parse_events, ''))


@pytest.mark.skipif(not hasattr(sys, "get_int_max_str_digits"),
                    reason="no int max str digits limit")
def test_kvitems_int_exceeding_max_str_digits(adaptor):
    """Check that kvitems raises int()'s ValueError for integers beyond sys.get_int_max_str_digits()"""
    json = b'{"a": %s}' % (b'1' * (sys.get_int_max_str_digits() + 1))
    with pytest.raises(ValueError, match="integer string conversion"):
        adaptor.kvitems(json, '')
