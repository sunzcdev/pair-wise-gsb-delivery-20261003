"""Rebind a virtual environment that was copied to a new location.

Virtual environments record their creation location in a few files that
``virtualenv`` itself generates (some activation scripts and the historical
``command`` entry of ``pyvenv.cfg``).  When an environment is copied to
another path - for example when a CI artifact is unpacked elsewhere - those
records go stale.  This module offers a single, explicit entry point to
rebind such a copy:

1. the caller-facing checks validate the identity of the base Python the
   environment was created from, so a copy is never rebound against the
   wrong interpreter,
2. only files generated by ``virtualenv`` itself are rewritten,
3. files written by other tools (for example ``pip`` generated console
   script launchers) and entries whose ownership cannot be confirmed are
   reported separately and left untouched,
4. when any check fails nothing is written, so the target stays readable.

Use it either as a library via :func:`rebind` or from the command line::

    python -m virtualenv.rebind "C:\\ci artifacts\\my env"
"""

from __future__ import annotations

import argparse
import logging
import os
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Final

if TYPE_CHECKING:
    from collections.abc import Sequence

LOGGER: Final[logging.Logger] = logging.getLogger(__name__)  # simplint: ignore[module-variable-prefix]  # existing API

#: activation script names virtualenv may generate; only these (plus ``pyvenv.cfg``) are ever rewritten
_ACTIVATOR_NAMES: Final[tuple[str, ...]] = (
    "activate",
    "activate.bat",
    "activate.csh",
    "activate.fish",
    "activate.nu",
    "activate.xsh",
    "activate.ps1",
    "Activate.ps1",
    "deactivate.bat",
    "deactivate.csh",
    "pydoc.bat",
    "activate_this.py",
)

#: folders, relative to the environment root, where activators live (Windows first)
_SCRIPT_DIR_NAMES: Final[tuple[str, ...]] = ("Scripts", "bin", "sbin")

#: extracts the environment root recorded by the activator templates
_ACTIVATOR_PATTERNS: Final[tuple[re.Pattern[str], ...]] = tuple(
    re.compile(pattern, re.IGNORECASE | re.MULTILINE)
    for pattern in (
        r"""^[ \t]*@?set "VIRTUAL_ENV=(?P<path>[^"]+)"[ \t]*$""",  # batch
        r"""^[ \t]*VIRTUAL_ENV=['"](?P<path>[^'"]+)['"][ \t]*$""",  # bash / sh
        r"""^[ \t]*let virtual_env = r#'(?P<path>[^']+)'#[ \t]*$""",  # nushell
        r"""^[ \t]*set -gx VIRTUAL_ENV ['"]?(?P<path>[^'"]+?)['"]?[ \t]*$""",  # fish
        r"""^[ \t]*setenv VIRTUAL_ENV ['"]?(?P<path>[^'"]+?)['"]?[ \t]*$""",  # csh
        r"""^[ \t]*\$VIRTUAL_ENV = r?['"](?P<path>[^'"]+)['"][ \t]*$""",  # xonsh
    )
)

#: suffixes of launcher files produced by installers (pip/distlib), never by virtualenv
_EXTERNAL_SUFFIXES: Final[frozenset[str]] = frozenset({".exe", ".dll", ".pyd", ".so"})

#: a drive, rooted or UNC path, used to tell recorded locations from computed shell values
_ABSOLUTE_PATH: Final[re.Pattern[str]] = re.compile(r"^(?:[A-Za-z]:[\\/]|/|\\\\)")


def _path_spellings(old: str, new: str) -> list[tuple[bytes, bytes]]:
    """Give the (old, new) byte pairs for every spelling the activator templates use for a path."""
    pairs = [
        (old, new),  # batch, bash, nushell, pyvenv.cfg and installer shebangs
        (old.replace("\\", "\\\\"), new.replace("\\", "\\\\")),  # escaped backslashes, e.g. JSON style records
        (  # fish quotes every backslash as '\\\\' inside a single quoted literal
            "'" + old.replace("\\", "'\\\\'") + "'",
            "'" + new.replace("\\", "'\\\\'") + "'",
        ),
    ]
    return [(o.encode("utf-8"), n.encode("utf-8")) for o, n in pairs]


class RebindError(RuntimeError):
    """Raised when a check fails; the target environment is guaranteed to be left untouched."""


@dataclass
class RebindReport:
    """The outcome of a :func:`rebind` call.

    :param env_dir: the environment root that was rebound
    :param old_dir: the location the environment was created at
    :param base_python: the base interpreter the environment was checked against
    :param updated: environment-relative paths of virtualenv-generated files that were rewritten
    :param external: environment-relative paths of files still referencing ``old_dir`` that other tools own
    :param unconfirmed: environment-relative paths of files still referencing ``old_dir`` of unknown origin
    :param changed: ``False`` when the environment already pointed at its current location
    """

    env_dir: Path
    old_dir: Path
    base_python: Path
    updated: list[str] = field(default_factory=list)
    external: list[str] = field(default_factory=list)
    unconfirmed: list[str] = field(default_factory=list)
    changed: bool = True

    def __str__(self) -> str:
        lines = [
            f"rebound virtual environment at {self.env_dir}",
            f"  previous location {self.old_dir}",
            f"  base python {self.base_python}",
        ]
        if not self.changed:
            lines.append("  already up to date, nothing to do")
            return "\n".join(lines)
        lines.append(f"  updated virtualenv files: {', '.join(self.updated) if self.updated else '(none)'}")
        if self.external:
            lines.append(f"  external files left untouched: {', '.join(self.external)}")
        if self.unconfirmed:
            lines.append(f"  unconfirmed entries left untouched: {', '.join(self.unconfirmed)}")
        return "\n".join(lines)


def rebind(env_dir: Path | str, *, check_only: bool = False) -> RebindReport:
    """Rebind the environment at ``env_dir`` to its current location.

    :param env_dir: the environment root after it was copied to its new path
    :param check_only: when ``True`` only run the checks and compute the plan, writing nothing
    :returns: a report of what was updated and what was deliberately left alone
    :raises RebindError: when any identity or consistency check fails; nothing is written in that case
    """
    env = Path(env_dir).resolve()
    cfg = _check_layout(env)
    base_python = _check_base_python(env, cfg)
    old_dir = _detect_previous_location(env)
    _check_env_python(env)
    new_text, old_text = str(env), str(old_dir)
    if os.path.normcase(new_text) == os.path.normcase(old_text):
        return RebindReport(env, old_dir, base_python, changed=False)
    plan = _plan_updates(env, old_text, new_text)
    report = RebindReport(env, old_dir, base_python, updated=sorted(plan), changed=True)
    if not check_only:
        _apply(env, plan)
    report.external, report.unconfirmed = _scan_remaining(env, old_text, rewritten=set(plan))
    return report


def _check_layout(env: Path):  # noqa: ANN202 # the PyEnvCfg import is deferred to keep module import cheap
    if not env.is_dir():
        msg = f"environment folder does not exist: {env}"
        raise RebindError(msg)
    from virtualenv.create.pyenv_cfg import PyEnvCfg  # ruff:ignore[import-outside-top-level]  # deferred import

    cfg = PyEnvCfg.from_folder(env)
    if "home" not in cfg.content:
        msg = f"not a virtualenv created environment, pyvenv.cfg with a home key is missing: {env}"
        raise RebindError(msg)
    if _script_dir(env) is None:
        msg = f"environment has no script folder ({', '.join(_SCRIPT_DIR_NAMES)}): {env}"
        raise RebindError(msg)
    return cfg


def _script_dir(env: Path) -> Path | None:
    for name in _SCRIPT_DIR_NAMES:
        candidate = env / name
        if candidate.is_dir():
            return candidate
    return None


def _check_base_python(env: Path, cfg) -> Path:  # noqa: ANN001, ANN202 # cfg is a PyEnvCfg, imported lazily
    base_executable = cfg.content.get("base-executable")
    if base_executable:
        candidate = Path(base_executable)
    else:
        home = Path(cfg.content["home"])
        candidate = home / ("python.exe" if sys.platform == "win32" else "python")
    if not candidate.is_file():
        msg = f"base python recorded in pyvenv.cfg is missing: {candidate}"
        raise RebindError(msg)
    out = _run_python(candidate, "import json, sys; print(json.dumps([sys.version_info[:3], sys.prefix]))")
    try:
        import json  # ruff:ignore[import-outside-top-level]  # deferred import

        version, prefix = json.loads(out)
    except ValueError as exception:
        msg = f"could not inspect base python {candidate}: {exception}"
        raise RebindError(msg) from exception
    recorded = cfg.content.get("version_info", "").split(".")
    if recorded and [str(i) for i in version] != recorded[:3]:
        msg = f"base python {candidate} is {'.'.join(map(str, version))} but pyvenv.cfg records {cfg.content['version_info']}"
        raise RebindError(msg)
    home = cfg.content["home"]
    if os.path.normcase(os.path.abspath(prefix)) != os.path.normcase(os.path.abspath(home)):
        msg = f"base python {candidate} reports prefix {prefix} but pyvenv.cfg records home {home}"
        raise RebindError(msg)
    return candidate


def _check_env_python(env: Path) -> None:
    scripts = _script_dir(env)
    assert scripts is not None  # noqa: S101 # guarded by _check_layout
    names = ("python.exe", "python") if sys.platform == "win32" else ("python", "python3")
    executable = next((scripts / name for name in names if (scripts / name).is_file()), None)
    if executable is None:
        msg = f"no python executable found in {scripts}"
        raise RebindError(msg)
    prefix = _run_python(executable, "import sys; print(sys.prefix)").strip()
    if os.path.normcase(os.path.abspath(prefix)) != os.path.normcase(str(env)):
        msg = f"environment python {executable} reports prefix {prefix}, expected {env}"
        raise RebindError(msg)


def _run_python(executable: Path, code: str) -> str:
    try:
        process = subprocess.run(  # noqa: S603 # the executable is the validated interpreter itself
            [str(executable), "-c", code],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as exception:
        msg = f"failed to run {executable}: {exception}"
        raise RebindError(msg) from exception
    if process.returncode != 0:
        msg = f"{executable} failed to identify itself: {process.stderr.strip()}"
        raise RebindError(msg)
    return process.stdout.strip()


def _detect_previous_location(env: Path) -> Path:
    scripts = _script_dir(env)
    assert scripts is not None  # noqa: S101 # guarded by _check_layout
    candidates: dict[str, str] = {}
    for name in _ACTIVATOR_NAMES:
        path = scripts / name
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for pattern in _ACTIVATOR_PATTERNS:
            for match in pattern.finditer(text):
                candidate = match.group("path")
                # templates also assign computed values such as "$CURRENT_ENV"; only real paths count
                if not _ABSOLUTE_PATH.match(candidate):
                    continue
                candidates.setdefault(os.path.normcase(candidate), candidate)
    if not candidates:
        msg = f"could not find a recorded location in the activation scripts of {env}"
        raise RebindError(msg)
    if len(candidates) > 1:
        locations = ", ".join(sorted(candidates.values()))
        msg = f"activation scripts of {env} disagree on the previous location: {locations}"
        raise RebindError(msg)
    return Path(next(iter(candidates.values())))


def _plan_updates(env: Path, old: str, new: str) -> dict[str, bytes]:
    plan: dict[str, bytes] = {}
    targets = [env / "pyvenv.cfg"]
    scripts = _script_dir(env)
    assert scripts is not None  # noqa: S101 # guarded by _check_layout
    targets.extend(scripts / name for name in _ACTIVATOR_NAMES)
    spellings = _path_spellings(old, new)
    for path in targets:
        if not path.is_file():
            continue
        raw = path.read_bytes()
        updated = raw
        for old_bytes, new_bytes in spellings:
            updated = updated.replace(old_bytes, new_bytes)
        if updated != raw:
            plan[str(path.relative_to(env))] = updated
    return plan


def _apply(env: Path, plan: dict[str, bytes]) -> None:
    originals: dict[Path, bytes] = {}
    try:
        for relative, content in plan.items():
            path = env / relative
            originals[path] = path.read_bytes()
            fd, temp_name = tempfile.mkstemp(dir=path.parent, prefix=path.name, suffix=".rebind")
            try:
                with os.fdopen(fd, "wb") as stream:
                    stream.write(content)
                os.replace(temp_name, path)
            except BaseException:
                if os.path.exists(temp_name):
                    os.unlink(temp_name)
                raise
            LOGGER.debug("rewrote %s", path)
    except BaseException as exception:
        for path, content in originals.items():
            try:
                path.write_bytes(content)
            except OSError:  # best effort rollback, the original error is the one to report
                LOGGER.warning("failed to restore %s", path)
        msg = f"failed to rewrite {env}, rolled back: {exception}"
        raise RebindError(msg) from exception


def _scan_remaining(env: Path, old: str, *, rewritten: set[str]) -> tuple[list[str], list[str]]:
    external: list[str] = []
    unconfirmed: list[str] = []
    spellings = [old_bytes for old_bytes, _ in _path_spellings(old, old)]
    for root, dirs, files in os.walk(env):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for name in files:
            path = Path(root) / name
            relative = str(path.relative_to(env))
            if relative in rewritten:
                continue
            try:
                raw = path.read_bytes()
            except OSError:
                continue
            if not any(spelling in raw for spelling in spellings):
                continue
            if path.suffix.lower() in _EXTERNAL_SUFFIXES or raw.startswith(b"#!"):
                external.append(relative)
            else:
                unconfirmed.append(relative)
    return sorted(external), sorted(unconfirmed)


def main(argv: Sequence[str] | None = None) -> int:
    """Command line entry point of ``python -m virtualenv.rebind``."""
    parser = argparse.ArgumentParser(
        prog="virtualenv-rebind",
        description="Rebind a copied virtual environment to its current location.",
    )
    parser.add_argument("env", help="the environment folder after it was copied to its new path")
    parser.add_argument(
        "--check",
        action="store_true",
        help="only run the checks and report what would change, writing nothing",
    )
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.WARNING, format="%(message)s")
    try:
        report = rebind(args.env, check_only=args.check)
    except RebindError as exception:
        print(f"rebind failed, target left untouched: {exception}", file=sys.stderr)  # ruff:ignore[print]  # CLI output
        return 1
    print(report)  # ruff:ignore[print]  # the report is the CLI output
    return 0


if __name__ == "__main__":
    sys.exit(main())


