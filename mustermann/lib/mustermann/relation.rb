# frozen_string_literal: true
require 'mustermann/error'
require 'mustermann/relation/ir'
require 'mustermann/relation/regexp_parser'
require 'mustermann/relation/builder'
require 'mustermann/relation/analyzer'

module Mustermann
  # Result of a static relationship analysis between two patterns.
  #
  # Answers two questions about the languages of two path patterns:
  #
  # * {#intersect?} — do the two patterns match any common path?
  # * {#subset?} — does every path matched by the first pattern also match the second?
  #
  # Either answer may be +nil+ (unknown) when a pattern uses constructs that cannot be
  # analyzed reliably, in which case {#reasons} explains why. Concrete evidence paths
  # ({#witness}, {#counterexample}) are verified against the real pattern objects with
  # the existing matching interface, so every reported path can be handed straight back
  # to {Mustermann::Pattern#===} or {Mustermann::Pattern#match}.
  #
  # @see Mustermann.relate
  # @see Mustermann::Pattern#relation_to
  class Relation
    # @return [Mustermann::Pattern] the first pattern
    attr_reader :left

    # @return [Mustermann::Pattern] the second pattern
    attr_reader :right

    # @return [String, nil] a concrete path matched by both patterns when they
    #   intersect, or nil when proven disjoint
    attr_reader :witness

    # @return [String, nil] a concrete path matched by the left pattern but not the
    #   right one, proving the left is not contained in the right
    attr_reader :counterexample

    # @return [Array<String>] human-readable reasons for answers being unknown
    attr_reader :reasons

    # @param left [Mustermann::Pattern]
    # @param right [Mustermann::Pattern]
    def initialize(left, right)
      @left, @right = left, right
      @reasons = []
      analyze
    end

    # @return [Boolean, nil] whether the patterns share at least one concrete path.
    #   +nil+ means this could not be decided.
    def intersect?
      @intersect
    end

    # @return [Boolean, nil] whether every path matched by the left pattern is also
    #   matched by the right one. +nil+ means this could not be decided.
    def subset?
      @subset
    end

    # @return [Boolean, nil] whether the two patterns match exactly the same paths.
    def equivalent?
      return nil if @subset.nil?
      return false unless @subset
      reverse.subset?
    end

    # @return [Boolean] whether either question could not be decided
    def unknown?
      @intersect.nil? || @subset.nil?
    end

    # @return [Hash{Symbol => Object}] compact representation
    def to_h
      {
        intersect: @intersect,
        subset: @subset,
        witness: witness,
        counterexample: counterexample,
        reasons: reasons
      }.reject { |_, value| value.nil? || (value.is_a?(Array) && value.empty?) }
    end

    def inspect
      details = [
        "intersect=#{@intersect.inspect}",
        "subset=#{@subset.inspect}",
        witness ? "witness=#{witness.inspect}" : nil,
        counterexample ? "counterexample=#{counterexample.inspect}" : nil
      ].compact.join(' ')
      "#<#{self.class.name} #{left.simple_inspect} vs #{right.simple_inspect} #{details}>"
    end

    private

    def reverse
      @reverse ||= self.class.new(right, left)
    end

    def analyze
      left_node,  left_reasons  = Builder.build(left)
      right_node, right_reasons = Builder.build(right)
      @reasons.concat(left_reasons.map { |reason| "left pattern: #{reason}" })
      @reasons.concat(right_reasons.map { |reason| "right pattern: #{reason}" })
      @reasons.uniq!

      if left_node.nil? || right_node.nil?
        @intersect = @subset = nil
        return
      end

      analyzer = Analyzer.new(left_node, right_node)

      found_witness = analyzer.witness_path
      if found_witness && verified?(found_witness, true, true)
        @witness = found_witness
        @intersect = true
      elsif found_witness.nil? && analyzer.intersection == :disjoint
        @intersect = false
      else
        @intersect = nil
        @reasons << 'intersection witness generated by the analyzer was rejected by the matchers'
      end

      found_counter = analyzer.counterexample
      if found_counter && verified?(found_counter, true, false)
        @counterexample = found_counter
        @subset = false
      elsif found_counter.nil? && analyzer.subset == :subset
        @subset = true
      else
        @subset = nil
        @reasons << 'containment counterexample generated by the analyzer was rejected by the matchers'
      end
    end

    # Verifies a generated path against the real matching interface. This guarantees
    # that every reported piece of evidence can be handed back to the patterns.
    def verified?(path, expected_left, expected_right)
      (left === path) == expected_left && (right === path) == expected_right
    rescue Encoding::CompatibilityError, Encoding::UndefinedConversionError
      # The generated path uses characters incompatible with a matcher's source
      # encoding; it cannot be used as evidence. Treated as a rejected witness.
      false
    end
  end
end
